DROP POLICY IF EXISTS "fp_farm_bcnc_ct_update_auth" ON public.fp_farm_bao_cao_nhan_cong_ct;
DROP POLICY IF EXISTS "fp_farm_bcnc_ct_delete_auth" ON public.fp_farm_bao_cao_nhan_cong_ct;

CREATE POLICY "fp_farm_bcnc_ct_select_auth" ON public.fp_farm_bao_cao_nhan_cong_ct
  FOR SELECT TO authenticated USING (true);

CREATE POLICY "fp_farm_bcnc_ct_insert_auth" ON public.fp_farm_bao_cao_nhan_cong_ct
