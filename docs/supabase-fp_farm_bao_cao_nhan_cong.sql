CREATE TABLE IF NOT EXISTS public.fp_farm_bao_cao_nhan_cong_ct (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_bao_cao bigint NOT NULL REFERENCES public.fp_farm_bao_cao_nhan_cong(id) ON DELETE CASCADE,
  loai_chuyen text NOT NULL,
  sl_cong_ngay numeric(18,4) NOT NULL DEFAULT 0,
  sl_cong_nua numeric(18,4) NOT NULL DEFAULT 0,
  sl_tang_ca numeric(18,4) NOT NULL DEFAULT 0,
  so_gio_tc numeric(18,4) NOT NULL DEFAULT 0,
  ghi_chu text,
  thu_tu integer NOT NULL DEFAULT 0,
  CONSTRAINT fp_farm_bcnc_ct_loai_chk CHECK (
    loai_chuyen IN (
      'XAN_NAI',
      'TIA_DANH_GIA',
      'CAN_TEM_DONG_THUNG',
      'KHO_HUT_CHAN_KHONG',
      'CONG_TANG_CUONG',
      'CONG_DINH_BIEN_KHONG_SAN_XUAT'
    )
  )
);

COMMENT ON TABLE public.fp_farm_bao_cao_nhan_cong_ct IS 'Chi tiết nhân công theo từng chuyền';
COMMENT ON COLUMN public.fp_farm_bao_cao_nhan_cong_ct.loai_chuyen IS 'Mã chuyền cố định (6 loại)';
COMMENT ON COLUMN public.fp_farm_bao_cao_nhan_cong_ct.sl_cong_ngay IS 'SL công ngày';
COMMENT ON COLUMN public.fp_farm_bao_cao_nhan_cong_ct.sl_cong_nua IS 'SL công nửa';
COMMENT ON COLUMN public.fp_farm_bao_cao_nhan_cong_ct.sl_tang_ca IS 'SL tăng ca';
COMMENT ON COLUMN public.fp_farm_bao_cao_nhan_cong_ct.so_gio_tc IS 'Số giờ tăng ca';
COMMENT ON COLUMN public.fp_farm_bao_cao_nhan_cong_ct.ghi_chu IS 'Ghi chú dòng chuyền; cho phép nhiều dòng (text)';

CREATE INDEX IF NOT EXISTS idx_fp_farm_bcnc_ct_bao_cao ON public.fp_farm_bao_cao_nhan_cong_ct(id_bao_cao);

-- =============================================================================
-- Đồng bộ CHECK `loai_chuyen` (6 mã) — chạy luôn sau khi bảng con đã tồn tại.
-- Nếu DB cũ chỉ có 5 mã, INSERT chi tiết có dòng V sẽ trả HTTP 400 (violates check).
-- =============================================================================
ALTER TABLE public.fp_farm_bao_cao_nhan_cong_ct DROP CONSTRAINT IF EXISTS fp_farm_bcnc_ct_loai_chk;
ALTER TABLE public.fp_farm_bao_cao_nhan_cong_ct ADD CONSTRAINT fp_farm_bcnc_ct_loai_chk CHECK (
  loai_chuyen IN (
    'XAN_NAI',
    'TIA_DANH_GIA',
    'CAN_TEM_DONG_THUNG',
    'KHO_HUT_CHAN_KHONG',
    'CONG_TANG_CUONG',
    'CONG_DINH_BIEN_KHONG_SAN_XUAT'
  )
);

-- Quyền dùng sequence của cột IDENTITY — thiếu có thể gây lỗi khi INSERT (kèm RETURNING).
DO $bcnc_seq$
DECLARE
  seq text;
BEGIN
  seq := pg_get_serial_sequence('public.fp_farm_bao_cao_nhan_cong', 'id');
  IF seq IS NOT NULL THEN
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO authenticated', seq);
  END IF;
  seq := pg_get_serial_sequence('public.fp_farm_bao_cao_nhan_cong_ct', 'id');
  IF seq IS NOT NULL THEN
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO authenticated', seq);
  END IF;
END
$bcnc_seq$;

-- =============================================================================
-- RLS + GRANT (bắt buộc nếu bảng đã ENABLE ROW LEVEL SECURITY — tránh HTTP 403)
-- Chạy toàn bộ block sau trên Supabase SQL Editor (có thể chạy lại an toàn nhờ DROP IF EXISTS).
-- App dùng user đã đăng nhập → role `authenticated` trong JWT.
-- =============================================================================

ALTER TABLE public.fp_farm_bao_cao_nhan_cong ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fp_farm_bao_cao_nhan_cong_ct ENABLE ROW LEVEL SECURITY;

-- Tên policy cũ (comment trong bản trước) — xóa nếu từng tạo tay
DROP POLICY IF EXISTS "bcnc_select" ON public.fp_farm_bao_cao_nhan_cong;
DROP POLICY IF EXISTS "bcnc_mutate" ON public.fp_farm_bao_cao_nhan_cong;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.fp_farm_bao_cao_nhan_cong TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.fp_farm_bao_cao_nhan_cong_ct TO authenticated;

-- Bảng cha
DROP POLICY IF EXISTS "fp_farm_bcnc_select_auth" ON public.fp_farm_bao_cao_nhan_cong;
DROP POLICY IF EXISTS "fp_farm_bcnc_insert_auth" ON public.fp_farm_bao_cao_nhan_cong;
DROP POLICY IF EXISTS "fp_farm_bcnc_update_auth" ON public.fp_farm_bao_cao_nhan_cong;
