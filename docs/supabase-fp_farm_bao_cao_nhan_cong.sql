-- Farm: Báo cáo nhân công — phiếu theo ngày + chi tiết theo chuyền sản xuất
-- Bảng: fp_farm_bao_cao_nhan_cong (cha), fp_farm_bao_cao_nhan_cong_ct (con)
-- Chi tiết từng ô (CN ngày / CN nửa / tăng ca): docs/supabase-fp_farm_bao_cao_nhan_cong_ct_sub.sql
-- KPI / thưởng đã chuyển sang báo cáo sơ chế: docs/supabase-fp_farm_bao_cao_so_che_kpi.sql
-- Chạy sau khi đã có fp_var_chi_nhanh, fp_var_nhan_vien (nếu FK tham chiếu)
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.fp_farm_bao_cao_nhan_cong (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ngay date NOT NULL,
  id_chi_nhanh bigint NOT NULL REFERENCES public.fp_var_chi_nhanh(id) ON DELETE RESTRICT,
  ten_chi_nhanh text,
  ghi_chu text,
  id_nguoi_tao bigint REFERENCES public.fp_var_nhan_vien(id) ON DELETE SET NULL,
  trang_thai text NOT NULL DEFAULT 'mo' CHECK (trang_thai IN ('mo', 'khoa')),
  tg_tao timestamptz NOT NULL DEFAULT now(),
  tg_cap_nhat timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.fp_farm_bao_cao_nhan_cong IS 'Báo cáo nhân công theo ngày / chi nhánh';
COMMENT ON COLUMN public.fp_farm_bao_cao_nhan_cong.ngay IS 'Ngày báo cáo';
COMMENT ON COLUMN public.fp_farm_bao_cao_nhan_cong.ten_chi_nhanh IS 'Denormalize tên chi nhánh để list không cần join';
COMMENT ON COLUMN public.fp_farm_bao_cao_nhan_cong.ghi_chu IS 'Ghi chú phiếu; cho phép nhiều dòng (text)';
COMMENT ON COLUMN public.fp_farm_bao_cao_nhan_cong.trang_thai IS 'mo = đang mở (người tạo sửa/xóa); khoa = đã khóa (chỉ quản trị sửa/xóa trên app)';

CREATE INDEX IF NOT EXISTS idx_fp_farm_bcnc_ngay ON public.fp_farm_bao_cao_nhan_cong(ngay DESC);
CREATE INDEX IF NOT EXISTS idx_fp_farm_bcnc_chi_nhanh ON public.fp_farm_bao_cao_nhan_cong(id_chi_nhanh);

-- Một phiếu duy nhất theo cặp (chi nhánh, ngày)
CREATE UNIQUE INDEX IF NOT EXISTS uq_fp_farm_bcnc_chi_nhanh_ngay
  ON public.fp_farm_bao_cao_nhan_cong (id_chi_nhanh, ngay);

