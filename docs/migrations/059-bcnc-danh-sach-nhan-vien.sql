-- =============================================================================
-- 059-bcnc-danh-sach-nhan-vien.sql — Báo cáo nhân công: gõ tên nhân viên theo chuyền
--
-- Tờ chấm công giấy của nhà sơ chế liệt kê từng người (họ tên, vị trí, sáng/chiều, tăng ca).
-- Form báo cáo nhân công cho gõ tên giống ô lô ở Đánh giá đầu vào: chọn tên có sẵn hoặc gõ tên
-- mới → tên mới tự lưu vào danh mục nhân viên của chi nhánh khi lưu phiếu.
--
-- Chuyền có danh sách tên thì app tự sinh dòng _ct_sub (gom theo số giờ) từ danh sách → bảng
-- _ct / _ct_sub, KPI, thống kê, in, xuất Excel giữ nguyên. Bảng _nv chỉ là nguồn để hiện / sửa lại tên.
--
-- Chạy: bash scripts/db-backup.sh truoc-059
--       bash scripts/db-sql.sh -v ON_ERROR_STOP=1 -f docs/migrations/059-bcnc-danh-sach-nhan-vien.sql
-- =============================================================================
BEGIN;

-- 1) Danh mục nhân viên sơ chế theo chi nhánh (công nhân không cần tài khoản app).
CREATE TABLE IF NOT EXISTS public.fp_var_nhan_vien_so_che (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chi_nhanh bigint NOT NULL REFERENCES public.fp_var_chi_nhanh(id) ON DELETE RESTRICT,
    ho_ten text NOT NULL,
    vi_tri text,
    loai_chuyen text,
    dang_dung boolean DEFAULT true NOT NULL,
    thu_tu integer DEFAULT 0 NOT NULL,
    tg_tao timestamp with time zone DEFAULT now() NOT NULL,
    tg_cap_nhat timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT fp_var_nvsc_ten_check CHECK (btrim(ho_ten) <> ''),
    CONSTRAINT fp_var_nvsc_loai_chuyen_chk CHECK (loai_chuyen IS NULL OR loai_chuyen = ANY (ARRAY[
      'XAN_NAI', 'TIA_DANH_GIA', 'CAN_TEM_DONG_THUNG', 'KHO_HUT_CHAN_KHONG', 'CONG_TANG_CUONG',
      'CONG_DINH_BIEN_KHONG_SAN_XUAT']))
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_fp_var_nvsc_cn_ten
  ON public.fp_var_nhan_vien_so_che (id_chi_nhanh, lower(ho_ten));

COMMENT ON TABLE public.fp_var_nhan_vien_so_che IS 'Báo cáo nhân công — danh mục nhân viên sơ chế theo chi nhánh (gõ tên, không cần tài khoản)';
COMMENT ON COLUMN public.fp_var_nhan_vien_so_che.vi_tri IS 'Vị trí công việc mặc định (Cân, Tỉa nải, Đóng thùng…) — chép vào phiếu khi chọn tên';
COMMENT ON COLUMN public.fp_var_nhan_vien_so_che.loai_chuyen IS 'Chuyền hay làm — dùng cho nút «Lấy cả nhóm của chuyền»';

-- 2) Người trong phiếu: thuộc một dòng chuyền (_ct). Sửa phiếu xoá _ct rồi chèn lại → CASCADE dọn luôn.
CREATE TABLE IF NOT EXISTS public.fp_farm_bao_cao_nhan_cong_nv (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bcnc_ct bigint NOT NULL REFERENCES public.fp_farm_bao_cao_nhan_cong_ct(id) ON DELETE CASCADE,
    id_nhan_vien bigint REFERENCES public.fp_var_nhan_vien_so_che(id) ON DELETE SET NULL,
    ho_ten text NOT NULL,
    vi_tri text,
    cham_cong text NOT NULL,
    so_gio_cong numeric(18,4) DEFAULT 0 NOT NULL,
    so_gio_tc numeric(18,4) DEFAULT 0 NOT NULL,
    ghi_chu text,
    thu_tu integer DEFAULT 0 NOT NULL,
    CONSTRAINT fp_farm_bcnc_nv_ten_check CHECK (btrim(ho_ten) <> ''),
    CONSTRAINT fp_farm_bcnc_nv_cham_cong_chk CHECK (cham_cong = ANY (ARRAY['CA_NGAY', 'NUA_NGAY'])),
    CONSTRAINT fp_farm_bcnc_nv_gio_nonneg CHECK (so_gio_cong >= 0 AND so_gio_tc >= 0)
);

CREATE INDEX IF NOT EXISTS idx_fp_farm_bcnc_nv_ct ON public.fp_farm_bao_cao_nhan_cong_nv (id_bcnc_ct, thu_tu);
CREATE INDEX IF NOT EXISTS idx_fp_farm_bcnc_nv_nhan_vien ON public.fp_farm_bao_cao_nhan_cong_nv (id_nhan_vien);

COMMENT ON TABLE public.fp_farm_bao_cao_nhan_cong_nv IS 'Báo cáo nhân công — tên từng người theo dòng chuyền; app sinh _ct_sub từ đây';
COMMENT ON COLUMN public.fp_farm_bao_cao_nhan_cong_nv.ho_ten IS 'Tên lúc lưu phiếu (đổi tên trong danh mục không đổi phiếu cũ)';
COMMENT ON COLUMN public.fp_farm_bao_cao_nhan_cong_nv.cham_cong IS 'CA_NGAY = cả ngày, NUA_NGAY = nửa ngày';

CREATE OR REPLACE TRIGGER trg_update_tg_cap_nhat BEFORE UPDATE ON public.fp_var_nhan_vien_so_che
  FOR EACH ROW EXECUTE FUNCTION public.update_tg_cap_nhat_column();

-- 3) RLS + GRANT (khuôn migration 052). Tên mới tự thêm khi lưu phiếu → ai tạo / sửa phiếu được
--    thì thêm / sửa danh mục được; xoá hẳn khỏi danh mục chỉ quản trị (bình thường bỏ «Đang dùng»).
DO $$
DECLARE
  c_mod constant text := 'quan-ly-nha-so-che/bao-cao-nhan-cong';
  c_xem constant text := 'ARRAY[''view'', ''create'', ''update'', ''delete'', ''approve'', ''admin'', ''all'']';
  r record;
BEGIN
  FOR r IN
    SELECT * FROM (VALUES
      ('fp_var_nhan_vien_so_che',      'fp_var_nvsc',      'ARRAY[''create'', ''update'', ''admin'', ''all'']', 'ARRAY[''create'', ''update'', ''admin'', ''all'']', 'ARRAY[''admin'', ''all'']'),
      ('fp_farm_bao_cao_nhan_cong_nv', 'fp_farm_bcnc_nv',  'ARRAY[''create'', ''update'', ''admin'', ''all'']', 'ARRAY[''create'', ''update'', ''admin'', ''all'']', 'ARRAY[''create'', ''update'', ''delete'', ''admin'', ''all'']')
    ) AS t(bang, ten, q_ins, q_upd, q_del)
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', r.bang);

    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_select_quyen', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_insert_quyen', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_update_quyen', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_delete_quyen', r.bang);

    EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_select_quyen', r.bang, c_mod, c_xem);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR INSERT TO authenticated '
                   'WITH CHECK ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_insert_quyen', r.bang, c_mod, r.q_ins);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR UPDATE TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s))) '
                   'WITH CHECK ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_update_quyen', r.bang, c_mod, r.q_upd, c_mod, r.q_upd);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR DELETE TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_delete_quyen', r.bang, c_mod, r.q_del);

    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon', r.bang);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.%I TO authenticated', r.bang);
    EXECUTE format('REVOKE ALL ON SEQUENCE public.%I FROM PUBLIC, anon', r.bang || '_id_seq');
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE public.%I TO authenticated', r.bang || '_id_seq');

    -- Nhật ký thay đổi (migration 016)
    EXECUTE format('CREATE OR REPLACE TRIGGER trg_nhat_ky_thay_doi AFTER INSERT OR UPDATE OR DELETE ON public.%I '
                   'FOR EACH ROW EXECUTE FUNCTION public.fn_ghi_nhat_ky_thay_doi()', r.bang);
  END LOOP;
END $$;

NOTIFY pgrst, 'reload schema';

COMMIT;
