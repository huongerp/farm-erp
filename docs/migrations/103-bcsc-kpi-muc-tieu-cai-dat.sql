-- =============================================================================
-- 103-bcsc-kpi-muc-tieu-cai-dat.sql — Báo cáo sơ chế: super admin cài mục tiêu KPI theo farm
--
-- Trước đây mục tiêu 2 dòng KPI preset (Năng suất sơ chế, Tỷ lệ nải chuỗi lỗi) nhập tay trên
-- từng phiếu. Nay super admin cài sẵn theo farm (chi nhánh) kèm NGÀY HIỆU LỰC: phiếu ngày D dùng
-- bản có ap_dung_tu lớn nhất ≤ D của farm đó. Thiếu bản = farm chưa cài → form giữ hành vi cũ.
-- Frontend lưu xong sẽ tính lại mục tiêu / % / đánh giá / thưởng của phiếu đã lưu trong khoảng
-- hiệu lực (bảng fp_farm_bao_cao_so_che_kpi đang mở RLS cho authenticated).
--
-- Đọc: ai xem được phiếu sơ chế. Ghi: chỉ super admin (fn_la_super_admin, migration 070).
-- Idempotent.
--
-- Chạy TRƯỚC frontend mới:
--   bash scripts/db-sql.sh -v ON_ERROR_STOP=1 -f docs/migrations/103-bcsc-kpi-muc-tieu-cai-dat.sql
-- =============================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS public.fp_var_bcsc_kpi_muc_tieu (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chi_nhanh bigint NOT NULL REFERENCES public.fp_var_chi_nhanh(id) ON DELETE CASCADE,
    ap_dung_tu date NOT NULL,
    muc_tieu_nang_suat numeric(10,4),
    muc_tieu_loi numeric(10,4),
    tg_tao timestamp with time zone DEFAULT now() NOT NULL,
    tg_cap_nhat timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT fp_var_bcsc_kmt_ns_chk CHECK (muc_tieu_nang_suat IS NULL OR muc_tieu_nang_suat > 0),
    CONSTRAINT fp_var_bcsc_kmt_loi_chk CHECK (muc_tieu_loi IS NULL OR muc_tieu_loi > 0),
    CONSTRAINT fp_var_bcsc_kmt_co_so_chk CHECK (muc_tieu_nang_suat IS NOT NULL OR muc_tieu_loi IS NOT NULL),
    CONSTRAINT uq_fp_var_bcsc_kmt UNIQUE (id_chi_nhanh, ap_dung_tu)
);
COMMENT ON TABLE public.fp_var_bcsc_kpi_muc_tieu IS
  'Báo cáo sơ chế — mục tiêu KPI theo farm + ngày hiệu lực (super admin cài); phiếu dùng bản ap_dung_tu lớn nhất ≤ ngày phiếu';
COMMENT ON COLUMN public.fp_var_bcsc_kpi_muc_tieu.muc_tieu_nang_suat IS 'Mục tiêu dòng Năng suất sơ chế (thùng); NULL = không cài';
COMMENT ON COLUMN public.fp_var_bcsc_kpi_muc_tieu.muc_tieu_loi IS 'Mục tiêu dòng Tỷ lệ nải chuỗi lỗi (%); NULL = không cài';

CREATE OR REPLACE TRIGGER trg_update_tg_cap_nhat BEFORE UPDATE ON public.fp_var_bcsc_kpi_muc_tieu
  FOR EACH ROW EXECUTE FUNCTION public.update_tg_cap_nhat_column();

DO $$
DECLARE
  c_mod constant text := 'quan-ly-nha-so-che/bao-cao-so-che';
  c_xem constant text := 'ARRAY[''view'', ''create'', ''update'', ''delete'', ''approve'', ''admin'', ''all'']';
BEGIN
  EXECUTE 'ALTER TABLE public.fp_var_bcsc_kpi_muc_tieu ENABLE ROW LEVEL SECURITY';

  EXECUTE 'DROP POLICY IF EXISTS bcsc_kmt_select_quyen ON public.fp_var_bcsc_kpi_muc_tieu';
  EXECUTE 'DROP POLICY IF EXISTS bcsc_kmt_insert_quyen ON public.fp_var_bcsc_kpi_muc_tieu';
  EXECUTE 'DROP POLICY IF EXISTS bcsc_kmt_update_quyen ON public.fp_var_bcsc_kpi_muc_tieu';
  EXECUTE 'DROP POLICY IF EXISTS bcsc_kmt_delete_quyen ON public.fp_var_bcsc_kpi_muc_tieu';

  EXECUTE format('CREATE POLICY %I ON public.fp_var_bcsc_kpi_muc_tieu FOR SELECT TO authenticated '
                 'USING ((SELECT public.fn_co_quyen_module(%L, %s)) OR (SELECT public.fn_la_super_admin()))',
                 'bcsc_kmt_select_quyen', c_mod, c_xem);
  EXECUTE 'CREATE POLICY bcsc_kmt_insert_quyen ON public.fp_var_bcsc_kpi_muc_tieu FOR INSERT TO authenticated '
          'WITH CHECK ((SELECT public.fn_la_super_admin()))';
  EXECUTE 'CREATE POLICY bcsc_kmt_update_quyen ON public.fp_var_bcsc_kpi_muc_tieu FOR UPDATE TO authenticated '
          'USING ((SELECT public.fn_la_super_admin())) WITH CHECK ((SELECT public.fn_la_super_admin()))';
  EXECUTE 'CREATE POLICY bcsc_kmt_delete_quyen ON public.fp_var_bcsc_kpi_muc_tieu FOR DELETE TO authenticated '
          'USING ((SELECT public.fn_la_super_admin()))';

  EXECUTE 'REVOKE ALL ON TABLE public.fp_var_bcsc_kpi_muc_tieu FROM PUBLIC, anon';
  EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.fp_var_bcsc_kpi_muc_tieu TO authenticated';
  EXECUTE 'REVOKE ALL ON SEQUENCE public.fp_var_bcsc_kpi_muc_tieu_id_seq FROM PUBLIC, anon';
  EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE public.fp_var_bcsc_kpi_muc_tieu_id_seq TO authenticated';

  -- Nhật ký thay đổi (migration 016) — đổi mục tiêu ảnh hưởng thưởng của mọi phiếu trong khoảng hiệu lực.
  EXECUTE 'CREATE OR REPLACE TRIGGER trg_nhat_ky_thay_doi AFTER INSERT OR UPDATE OR DELETE '
          'ON public.fp_var_bcsc_kpi_muc_tieu FOR EACH ROW '
          'EXECUTE FUNCTION public.fn_ghi_nhat_ky_thay_doi()';
END;
$$;

COMMIT;

NOTIFY pgrst, 'reload schema';
