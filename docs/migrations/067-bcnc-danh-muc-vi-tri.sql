-- =============================================================================
-- 067-bcnc-danh-muc-vi-tri.sql — Báo cáo nhân công: danh mục vị trí công việc dùng chung
--
-- Trước đây ô «Vị trí công việc» là text tự do (mỗi người một kiểu gõ: «tỉa nải»,
-- «NT TỈA», «tia nải»…). Migration này tạo danh mục chuẩn dùng chung toàn hệ thống để:
--   - nút Cài đặt trên danh sách phiếu sửa / thêm / ngừng dùng / xoá vị trí;
--   - dropdown trong form chỉ gợi ý danh sách chuẩn, gõ vị trí mới thì tự thêm vào danh mục.
--
-- Nạp sẵn các vị trí đang có trong danh mục nhân viên + phiếu cũ (gộp khoảng trắng,
-- không phân biệt hoa thường). Bản ghi cũ được đổi sang cách viết chuẩn của danh mục.
--
-- Chạy TRƯỚC frontend mới:
--   bash scripts/db-backup.sh truoc-067
--   bash scripts/db-sql.sh -v ON_ERROR_STOP=1 -f docs/migrations/067-bcnc-danh-muc-vi-tri.sql
-- =============================================================================
BEGIN;

-- 1) Danh mục vị trí dùng chung (không gắn chi nhánh).
CREATE TABLE IF NOT EXISTS public.fp_var_vi_tri_so_che (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten text NOT NULL,
    dang_dung boolean DEFAULT true NOT NULL,
    thu_tu integer DEFAULT 0 NOT NULL,
    tg_tao timestamp with time zone DEFAULT now() NOT NULL,
    tg_cap_nhat timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT fp_var_vtsc_ten_check CHECK (btrim(ten) <> '')
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_fp_var_vtsc_ten
  ON public.fp_var_vi_tri_so_che (lower(btrim(ten)));

COMMENT ON TABLE public.fp_var_vi_tri_so_che IS
  'Báo cáo nhân công — danh mục vị trí công việc dùng chung (Cân, Tỉa nải, Đóng thùng…)';
COMMENT ON COLUMN public.fp_var_vi_tri_so_che.dang_dung IS
  'Đang dùng (hiện trong gợi ý dropdown); tắt thay vì xoá để phiếu cũ giữ nguyên chữ';
COMMENT ON COLUMN public.fp_var_vi_tri_so_che.thu_tu IS
  'Thứ tự hiện trong danh sách Cài đặt / dropdown (nhỏ trước)';

CREATE OR REPLACE TRIGGER trg_update_tg_cap_nhat BEFORE UPDATE ON public.fp_var_vi_tri_so_che
  FOR EACH ROW EXECUTE FUNCTION public.update_tg_cap_nhat_column();

-- 2) Nạp vị trí đang dùng trong danh mục nhân viên + phiếu cũ.
--    Gộp khoảng trắng; trùng không phân biệt hoa thường thì chọn cách viết xuất hiện
--    nhiều nhất, ưu tiên bản viết hoa (NT TỈA, NP TỈA) khi cùng số lần.
WITH raw AS (
  SELECT btrim(regexp_replace(vi_tri, '\s+', ' ', 'g')) AS ten
    FROM public.fp_var_nhan_vien_so_che
   WHERE vi_tri IS NOT NULL AND btrim(vi_tri) <> ''
  UNION ALL
  SELECT btrim(regexp_replace(vi_tri, '\s+', ' ', 'g')) AS ten
    FROM public.fp_farm_bao_cao_nhan_cong_nv
   WHERE vi_tri IS NOT NULL AND btrim(vi_tri) <> ''
),
dem AS (
  SELECT ten, lower(ten) AS khoa, count(*) AS so_lan
    FROM raw
   GROUP BY ten, lower(ten)
),
chon AS (
  SELECT DISTINCT ON (khoa) ten, khoa
    FROM dem
   ORDER BY khoa,
            so_lan DESC,
            (ten = upper(ten)) DESC,
            length(ten) DESC,
            ten
)
INSERT INTO public.fp_var_vi_tri_so_che (ten, dang_dung, thu_tu)
SELECT ten, true, (row_number() OVER (ORDER BY ten) - 1)::integer
  FROM chon
ON CONFLICT DO NOTHING;

-- 3) Đổi cách viết cũ sang đúng tên chuẩn trong danh mục (chỉ khoảng trắng / hoa thường).
UPDATE public.fp_var_nhan_vien_so_che nv
   SET vi_tri = vt.ten
  FROM public.fp_var_vi_tri_so_che vt
 WHERE nv.vi_tri IS NOT NULL
   AND lower(btrim(regexp_replace(nv.vi_tri, '\s+', ' ', 'g'))) = lower(vt.ten)
   AND nv.vi_tri <> vt.ten;

UPDATE public.fp_farm_bao_cao_nhan_cong_nv nv
   SET vi_tri = vt.ten
  FROM public.fp_var_vi_tri_so_che vt
 WHERE nv.vi_tri IS NOT NULL
   AND lower(btrim(regexp_replace(nv.vi_tri, '\s+', ' ', 'g'))) = lower(vt.ten)
   AND nv.vi_tri <> vt.ten;

-- 4) Đổi tên vị trí trong Cài đặt → cập nhật luôn vị trí mặc định của danh mục nhân viên.
--    Phiếu cũ giữ nguyên chữ lúc lưu (đúng quy ước migration 059).
CREATE OR REPLACE FUNCTION public.fn_vtsc_doi_ten() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  IF NEW.ten IS DISTINCT FROM OLD.ten THEN
    UPDATE public.fp_var_nhan_vien_so_che
       SET vi_tri = NEW.ten
     WHERE vi_tri = OLD.ten;
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.fn_vtsc_doi_ten() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_vtsc_doi_ten() TO authenticated;

DROP TRIGGER IF EXISTS trg_vtsc_doi_ten ON public.fp_var_vi_tri_so_che;
CREATE TRIGGER trg_vtsc_doi_ten
  AFTER UPDATE OF ten ON public.fp_var_vi_tri_so_che
  FOR EACH ROW EXECUTE FUNCTION public.fn_vtsc_doi_ten();

-- 5) RLS + GRANT (khuôn migration 059). Ai xem phiếu thì xem danh mục; ai tạo / sửa phiếu
--    thì thêm / sửa vị trí; xoá hẳn chỉ quản trị (bình thường bấm «Ngừng dùng»).
DO $$
DECLARE
  c_mod constant text := 'quan-ly-nha-so-che/bao-cao-nhan-cong';
  c_xem constant text := 'ARRAY[''view'', ''create'', ''update'', ''delete'', ''approve'', ''admin'', ''all'']';
  r record;
BEGIN
  FOR r IN
    SELECT * FROM (VALUES
      ('fp_var_vi_tri_so_che', 'fp_var_vtsc', 'ARRAY[''create'', ''update'', ''admin'', ''all'']', 'ARRAY[''create'', ''update'', ''admin'', ''all'']', 'ARRAY[''create'', ''update'', ''admin'', ''all'']')
    ) AS t(bang, ten, q_ins, q_upd, q_del)
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', r.bang);

    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_select_quyen', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_insert_quyen', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_update_quyen', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_delete_quyen', r.bang);

    EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_select_quyen', r.bang, c_mod, c_xem);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR INSERT TO authenticated '
                   'WITH CHECK ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_insert_quyen', r.bang, c_mod, r.q_ins);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR UPDATE TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s))) '
                   'WITH CHECK ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_update_quyen', r.bang, c_mod, r.q_upd, c_mod, r.q_upd);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR DELETE TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_delete_quyen', r.bang, c_mod, r.q_del);

    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon', r.bang);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.%I TO authenticated', r.bang);
    EXECUTE format('REVOKE ALL ON SEQUENCE public.%I FROM PUBLIC, anon', r.bang || '_id_seq');
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE public.%I TO authenticated', r.bang || '_id_seq');

    -- Nhật ký thay đổi (migration 016)
    EXECUTE format('CREATE OR REPLACE TRIGGER trg_nhat_ky_thay_doi AFTER INSERT OR UPDATE OR DELETE ON public.%I '
                   'FOR EACH ROW EXECUTE FUNCTION public.fn_ghi_nhat_ky_thay_doi()', r.bang);
  END LOOP;
END $$;

COMMIT;
NOTIFY pgrst, 'reload schema';
