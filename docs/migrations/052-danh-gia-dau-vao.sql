-- 7) RLS + GRANT ----------------------------------------------------------------
-- Đọc: có bất kỳ quyền nào trên module (phạm vi chi nhánh lọc ở app như các module sơ chế khác).
-- Ghi danh mục (dialog Cài đặt ⚙): chỉ cấp cao / admin module (giống tiêu chí GSCL, migration 013).
-- Ghi phiếu: create / update / delete; bảng con là một phần của phiếu → ai tạo / sửa phiếu được thì ghi được.
-- (SELECT fn(...)) để Postgres tính quyền một lần / câu lệnh thay vì từng dòng.
DO $$
DECLARE
  c_mod constant text := 'quan-ly-nha-so-che/danh-gia-dau-vao';
  c_xem constant text := 'ARRAY[''view'', ''create'', ''update'', ''delete'', ''approve'', ''admin'', ''all'']';
  r record;
BEGIN
  FOR r IN
    SELECT * FROM (VALUES
      -- bang, viết tắt policy, quyền INSERT, quyền UPDATE, quyền DELETE
      ('fp_var_mau_day',       'fp_var_mau_day',   'ARRAY[''admin'', ''all'']', 'ARRAY[''admin'', ''all'']', 'ARRAY[''admin'', ''all'']'),
      ('fp_var_lo_thu_hoach',  'fp_var_lth',       'ARRAY[''admin'', ''all'']', 'ARRAY[''admin'', ''all'']', 'ARRAY[''admin'', ''all'']'),
      ('fp_var_dgdv_ly_do',    'fp_var_dgdv_ly_do','ARRAY[''admin'', ''all'']', 'ARRAY[''admin'', ''all'']', 'ARRAY[''admin'', ''all'']'),
      ('fp_farm_dgdv',         'fp_farm_dgdv',     'ARRAY[''create'', ''admin'', ''all'']', 'ARRAY[''update'', ''admin'', ''all'']', 'ARRAY[''delete'', ''admin'', ''all'']'),
      ('fp_farm_dgdv_cot',     'fp_farm_dgdv_cot', 'ARRAY[''create'', ''update'', ''admin'', ''all'']', 'ARRAY[''create'', ''update'', ''admin'', ''all'']', 'ARRAY[''create'', ''update'', ''delete'', ''admin'', ''all'']'),
      ('fp_farm_dgdv_lo',      'fp_farm_dgdv_lo',  'ARRAY[''create'', ''update'', ''admin'', ''all'']', 'ARRAY[''create'', ''update'', ''admin'', ''all'']', 'ARRAY[''create'', ''update'', ''delete'', ''admin'', ''all'']'),
      ('fp_farm_dgdv_lo_ngay', 'fp_farm_dgdv_ln',  'ARRAY[''create'', ''update'', ''admin'', ''all'']', 'ARRAY[''create'', ''update'', ''admin'', ''all'']', 'ARRAY[''create'', ''update'', ''delete'', ''admin'', ''all'']'),
      ('fp_farm_dgdv_dong',    'fp_farm_dgdv_dong','ARRAY[''create'', ''update'', ''admin'', ''all'']', 'ARRAY[''create'', ''update'', ''admin'', ''all'']', 'ARRAY[''create'', ''update'', ''delete'', ''admin'', ''all'']')
    ) AS t(bang, ten, q_ins, q_upd, q_del)
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', r.bang);

    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_select_quyen', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_insert_quyen', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_update_quyen', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_delete_quyen', r.bang);

    EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_select_quyen', r.bang, c_mod, c_xem);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR INSERT TO authenticated '
                   'WITH CHECK ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_insert_quyen', r.bang, c_mod, r.q_ins);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR UPDATE TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s))) '
                   'WITH CHECK ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_update_quyen', r.bang, c_mod, r.q_upd, c_mod, r.q_upd);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR DELETE TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_delete_quyen', r.bang, c_mod, r.q_del);

    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon', r.bang);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.%I TO authenticated', r.bang);
    EXECUTE format('REVOKE ALL ON SEQUENCE public.%I FROM PUBLIC, anon', r.bang || '_id_seq');
