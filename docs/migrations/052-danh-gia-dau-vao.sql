-- 4) Hàm tổng theo (ngày, chi nhánh) --------------------------------------------
-- Ngày chỉ thuộc đúng 1 tuần ISO → tối đa 1 phiếu / chi nhánh chứa ngày đó (UNIQUE nam, tuan, cn);
-- trigger 3c bảo đảm ngày của dòng nằm trong tuần phiếu. Tính cả phiếu đã khoá.
CREATE OR REPLACE FUNCTION public.fn_dgdv_tong_ngay(p_ngay date, p_id_chi_nhanh bigint)
    RETURNS TABLE (tong_thu bigint, ksc bigint)
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
  WITH p AS (
    SELECT id FROM public.fp_farm_dgdv
    WHERE id_chi_nhanh = p_id_chi_nhanh
      AND nam = extract(isoyear FROM p_ngay)::integer
      AND tuan = extract(week FROM p_ngay)::integer
  ),
  l AS (
    SELECT l.id FROM public.fp_farm_dgdv_lo l JOIN p ON p.id = l.id_phieu
  ),
  d AS (
    SELECT COALESCE(SUM(d.so_luong), 0)::bigint AS so_luong,
           COALESCE(SUM(d.so_luong_loi), 0)::bigint AS so_luong_loi
    FROM public.fp_farm_dgdv_dong d JOIN l ON l.id = d.id_phieu_lo
    WHERE d.ngay = p_ngay
  ),
  n AS (
    SELECT COALESCE(SUM(n.dut_day), 0)::bigint AS dut_day
    FROM public.fp_farm_dgdv_lo_ngay n JOIN l ON l.id = n.id_phieu_lo
    WHERE n.ngay = p_ngay
  )
  SELECT d.so_luong + n.dut_day, d.so_luong_loi FROM d CROSS JOIN n;
$$;

COMMENT ON FUNCTION public.fn_dgdv_tong_ngay(date, bigint) IS
  'Đánh giá đầu vào: tong_thu = Σ số lượng + Σ đứt dây; ksc = Σ số lượng lỗi của ngày + chi nhánh (0 nếu không có phiếu)';

REVOKE ALL ON FUNCTION public.fn_dgdv_tong_ngay(date, bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_dgdv_tong_ngay(date, bigint) TO authenticated;

-- 5) Đồng bộ sang Báo cáo sơ chế + Dự báo SL đóng thùng ---------------------------
-- 5a) Báo cáo sơ chế của (ngày, chi nhánh): cập nhật 2 dòng chỉ tiêu, thiếu dòng thì tạo
--     (thu_tu 2 / 3 khớp thứ tự SO_LIEU_BUONG_ROW_DEFS ở app). gia_tri thật do trigger 5d điền.
CREATE OR REPLACE FUNCTION public.fn_dgdv_dong_bo_bcsc(p_ngay date, p_id_chi_nhanh bigint)
    RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  v_thu bigint;
  v_ksc bigint;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.fp_farm_bao_cao_so_che WHERE ngay = p_ngay AND id_chi_nhanh = p_id_chi_nhanh) THEN
    RETURN;
  END IF;

  SELECT t.tong_thu, t.ksc INTO v_thu, v_ksc FROM public.fn_dgdv_tong_ngay(p_ngay, p_id_chi_nhanh) t;

  UPDATE public.fp_farm_bao_cao_so_che_ct ct
     SET gia_tri = CASE ct.ma_chi_tieu WHEN 'tong_buong_thu_hoach' THEN v_thu ELSE v_ksc END
    FROM public.fp_farm_bao_cao_so_che b
   WHERE b.id = ct.id_bao_cao
     AND b.ngay = p_ngay
     AND b.id_chi_nhanh = p_id_chi_nhanh
     AND ct.ma_chi_tieu IN ('tong_buong_thu_hoach', 'tong_buong_khong_so_che')
     AND ct.gia_tri IS DISTINCT FROM (CASE ct.ma_chi_tieu WHEN 'tong_buong_thu_hoach' THEN v_thu ELSE v_ksc END)::numeric;

  INSERT INTO public.fp_farm_bao_cao_so_che_ct (id_bao_cao, ma_chi_tieu, gia_tri, don_vi_tinh, thu_tu)
  SELECT b.id, m.ma, 0, 'Buồng', m.thu_tu
  FROM public.fp_farm_bao_cao_so_che b
  CROSS JOIN (VALUES ('tong_buong_thu_hoach'::text, 2), ('tong_buong_khong_so_che'::text, 3)) AS m(ma, thu_tu)
  WHERE b.ngay = p_ngay
    AND b.id_chi_nhanh = p_id_chi_nhanh
    AND NOT EXISTS (
      SELECT 1 FROM public.fp_farm_bao_cao_so_che_ct ct
      WHERE ct.id_bao_cao = b.id AND ct.ma_chi_tieu = m.ma);
END;
$$;

-- 5b) Cả hai module đích của (ngày, chi nhánh). gia_tri / tong_buong_nhap_thuc_te luôn được
--     trigger BEFORE (5d, 5e) tính lại, nên ở đây chỉ cần chạm vào dòng lệch số.
CREATE OR REPLACE FUNCTION public.fn_dgdv_dong_bo_ngay(p_ngay date, p_id_chi_nhanh bigint)
    RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  v_thu bigint;
BEGIN
  IF p_ngay IS NULL OR p_id_chi_nhanh IS NULL THEN
    RETURN;
  END IF;

  PERFORM public.fn_dgdv_dong_bo_bcsc(p_ngay, p_id_chi_nhanh);

  SELECT t.tong_thu INTO v_thu FROM public.fn_dgdv_tong_ngay(p_ngay, p_id_chi_nhanh) t;
  UPDATE public.fp_farm_du_bao_sl_dong_thung
     SET tong_buong_nhap_thuc_te = v_thu::integer
   WHERE ngay = p_ngay
     AND id_chi_nhanh = p_id_chi_nhanh
     AND tong_buong_nhap_thuc_te IS DISTINCT FROM v_thu::integer;
END;
$$;

-- 5c) Cả 7 ngày của một tuần phiếu.
-- (plpgsql + PERFORM: hàm sql trả void có thể chỉ lấy dòng đầu của SELECT.)
CREATE OR REPLACE FUNCTION public.fn_dgdv_dong_bo_tuan(p_nam integer, p_tuan integer, p_id_chi_nhanh bigint)
    RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  v_dau date := public.fn_dgdv_ngay_dau_tuan(p_nam, p_tuan);
BEGIN
  PERFORM public.fn_dgdv_dong_bo_ngay(v_dau + g.i, p_id_chi_nhanh)
  FROM generate_series(0, 6) AS g(i);
END;
$$;

-- Hàm nội bộ (chỉ trigger gọi, chạy với quyền chủ hàm) → không cấp cho ai.
REVOKE ALL ON FUNCTION public.fn_dgdv_dong_bo_bcsc(date, bigint) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.fn_dgdv_dong_bo_ngay(date, bigint) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.fn_dgdv_dong_bo_tuan(integer, integer, bigint) FROM PUBLIC, anon, authenticated;

-- 5d) Khoá số ở fp_farm_bao_cao_so_che_ct: 2 chỉ tiêu luôn = tổng phiếu, mọi giá trị gửi lên bị bỏ.
--     App lưu bằng cách xoá hết dòng chỉ tiêu rồi chèn lại (ctRowsFromForm), và trigger 5f / 5g
--     có thể đã tạo sẵn 2 dòng này → INSERT trùng (id_bao_cao, ma_chi_tieu) được đổi thành cập nhật
--     ghi chú / ĐVT / thứ tự lên dòng sẵn có rồi bỏ qua bản ghi chèn (RETURN NULL), thay vì lỗi UNIQUE.
CREATE OR REPLACE FUNCTION public.fn_dgdv_trg_bcsc_ct_khoa_so()
    RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  v_ngay date;
  v_cn bigint;
  v_thu bigint := 0;
  v_ksc bigint := 0;
BEGIN
  IF NEW.ma_chi_tieu NOT IN ('tong_buong_thu_hoach', 'tong_buong_khong_so_che') THEN
    RETURN NEW;
  END IF;

  SELECT b.ngay, b.id_chi_nhanh INTO v_ngay, v_cn FROM public.fp_farm_bao_cao_so_che b WHERE b.id = NEW.id_bao_cao;
  IF v_ngay IS NOT NULL THEN
    SELECT t.tong_thu, t.ksc INTO v_thu, v_ksc FROM public.fn_dgdv_tong_ngay(v_ngay, v_cn) t;
  END IF;
  NEW.gia_tri := CASE NEW.ma_chi_tieu WHEN 'tong_buong_thu_hoach' THEN v_thu ELSE v_ksc END;

  IF TG_OP = 'INSERT' AND EXISTS (
       SELECT 1 FROM public.fp_farm_bao_cao_so_che_ct ct
       WHERE ct.id_bao_cao = NEW.id_bao_cao AND ct.ma_chi_tieu = NEW.ma_chi_tieu) THEN
    UPDATE public.fp_farm_bao_cao_so_che_ct ct
       SET don_vi_tinh = NEW.don_vi_tinh,
           ghi_chu = NEW.ghi_chu,
           thu_tu = NEW.thu_tu,
           gia_tri = NEW.gia_tri
     WHERE ct.id_bao_cao = NEW.id_bao_cao AND ct.ma_chi_tieu = NEW.ma_chi_tieu;
    RETURN NULL;
  END IF;
  RETURN NEW;
END;
$$;

-- 5e) Khoá số ở fp_farm_du_bao_sl_dong_thung.tong_buong_nhap_thuc_te.
CREATE OR REPLACE FUNCTION public.fn_dgdv_trg_du_bao_khoa_so()
    RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
BEGIN
  NEW.tong_buong_nhap_thuc_te := COALESCE(
    (SELECT t.tong_thu FROM public.fn_dgdv_tong_ngay(NEW.ngay, NEW.id_chi_nhanh) t), 0)::integer;
  RETURN NEW;
END;
$$;

-- 5f) Phiếu Báo cáo sơ chế mới / đổi ngày, chi nhánh → tạo hoặc tính lại 2 dòng chỉ tiêu
