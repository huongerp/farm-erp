-- 6) Trigger nguồn: thay đổi trên phiếu Đánh giá đầu vào → đồng bộ ------------------
-- Trigger mức câu lệnh + bảng chuyển tiếp (transition table): lưu cả lưới một lần chỉ đồng bộ
-- mỗi cặp (ngày, chi nhánh) một lần. Postgres không cho một trigger có transition table bắt
-- nhiều sự kiện → mỗi bảng 3 trigger (INSERT / UPDATE / DELETE) dùng chung một hàm.
-- Ca cascade (xoá lô / phiếu): lúc trigger của bảng con chạy thì dòng cha đã mất, JOIN rỗng →
-- trigger mức câu lệnh của bảng cha (chạy SAU mọi cascade) đồng bộ lại cả tuần.

-- 6a) Ô lưới + đứt dây: cùng có (id_phieu_lo, ngay).
CREATE OR REPLACE FUNCTION public.fn_dgdv_trg_dong_bo_o()
    RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM public.fn_dgdv_dong_bo_ngay(x.ngay, x.id_chi_nhanh)
    FROM (SELECT DISTINCT r.ngay, p.id_chi_nhanh
          FROM new_rows r
          JOIN public.fp_farm_dgdv_lo l ON l.id = r.id_phieu_lo
          JOIN public.fp_farm_dgdv p ON p.id = l.id_phieu) x;
  ELSIF TG_OP = 'UPDATE' THEN
    PERFORM public.fn_dgdv_dong_bo_ngay(x.ngay, x.id_chi_nhanh)
    FROM (SELECT r.ngay, p.id_chi_nhanh
          FROM new_rows r
          JOIN public.fp_farm_dgdv_lo l ON l.id = r.id_phieu_lo
          JOIN public.fp_farm_dgdv p ON p.id = l.id_phieu
          UNION
          SELECT r.ngay, p.id_chi_nhanh
          FROM old_rows r
          JOIN public.fp_farm_dgdv_lo l ON l.id = r.id_phieu_lo
          JOIN public.fp_farm_dgdv p ON p.id = l.id_phieu) x;
  ELSE
    PERFORM public.fn_dgdv_dong_bo_ngay(x.ngay, x.id_chi_nhanh)
    FROM (SELECT DISTINCT r.ngay, p.id_chi_nhanh
          FROM old_rows r
          JOIN public.fp_farm_dgdv_lo l ON l.id = r.id_phieu_lo
          JOIN public.fp_farm_dgdv p ON p.id = l.id_phieu) x;
  END IF;
  RETURN NULL;
END;
$$;

-- 6b) Xoá lô / cột dây (bảng có id_phieu): ô con đã bị cascade → đồng bộ cả tuần phiếu.
--     INSERT không đổi tổng (chưa có ô con); UPDATE đổi id_phieu đã bị chặn (3b) → chỉ cần DELETE.
CREATE OR REPLACE FUNCTION public.fn_dgdv_trg_dong_bo_con_phieu()
    RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
BEGIN
  PERFORM public.fn_dgdv_dong_bo_tuan(p.nam, p.tuan, p.id_chi_nhanh)
  FROM public.fp_farm_dgdv p
  WHERE p.id IN (SELECT DISTINCT o.id_phieu FROM old_rows o);
  RETURN NULL;
END;
$$;

-- 6c) Phiếu: xoá → đồng bộ cả tuần của chi nhánh cũ (sau cascade). INSERT không đổi tổng.
CREATE OR REPLACE FUNCTION public.fn_dgdv_trg_dong_bo_phieu_xoa()
    RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
BEGIN
  PERFORM public.fn_dgdv_dong_bo_tuan(x.nam, x.tuan, x.id_chi_nhanh)
  FROM (SELECT DISTINCT o.nam, o.tuan, o.id_chi_nhanh FROM old_rows o) x;
  RETURN NULL;
END;
$$;

-- 6d) Phiếu: đổi chi nhánh / tuần → đồng bộ tuần cũ của chi nhánh cũ và tuần mới của chi nhánh mới.
CREATE OR REPLACE FUNCTION public.fn_dgdv_trg_dong_bo_phieu_sua()
    RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
BEGIN
  IF (NEW.nam, NEW.tuan, NEW.id_chi_nhanh) IS DISTINCT FROM (OLD.nam, OLD.tuan, OLD.id_chi_nhanh) THEN
    PERFORM public.fn_dgdv_dong_bo_tuan(OLD.nam, OLD.tuan, OLD.id_chi_nhanh);
    PERFORM public.fn_dgdv_dong_bo_tuan(NEW.nam, NEW.tuan, NEW.id_chi_nhanh);
  END IF;
  RETURN NULL;
END;
$$;

REVOKE ALL ON FUNCTION public.fn_dgdv_trg_dong_bo_o() FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.fn_dgdv_trg_dong_bo_con_phieu() FROM PUBLIC, anon;
