-- 3) Trigger kiểm dữ liệu phiếu ---------------------------------------------------
-- 3a) Phiếu: tuần phải tồn tại trong năm ISO; đổi tuần/năm thì mọi ngày đã nhập phải còn nằm
--     trong tuần mới; người tạo lấy từ JWT (không tin giá trị trình duyệt gửi).
CREATE OR REPLACE FUNCTION public.fn_dgdv_trg_kiem_phieu()
    RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  v_dau date := public.fn_dgdv_ngay_dau_tuan(NEW.nam, NEW.tuan);
BEGIN
  IF extract(isoyear FROM v_dau)::integer <> NEW.nam THEN
    RAISE EXCEPTION 'Năm % không có tuần ISO %', NEW.nam, NEW.tuan USING ERRCODE = '22023';
  END IF;

  IF TG_OP = 'INSERT' THEN
    NEW.id_nguoi_tao := COALESCE(public.nhan_vien_hien_tai_id(), NEW.id_nguoi_tao);
  ELSIF (NEW.nam, NEW.tuan) IS DISTINCT FROM (OLD.nam, OLD.tuan) THEN
    IF EXISTS (
         SELECT 1 FROM public.fp_farm_dgdv_lo l
         JOIN public.fp_farm_dgdv_dong d ON d.id_phieu_lo = l.id
         WHERE l.id_phieu = NEW.id AND d.ngay NOT BETWEEN v_dau AND v_dau + 6)
       OR EXISTS (
         SELECT 1 FROM public.fp_farm_dgdv_lo l
         JOIN public.fp_farm_dgdv_lo_ngay n ON n.id_phieu_lo = l.id
         WHERE l.id_phieu = NEW.id AND n.ngay NOT BETWEEN v_dau AND v_dau + 6) THEN
      RAISE EXCEPTION 'Phiếu đã có số liệu ngoài tuần %/% — xoá số liệu trước khi đổi tuần', NEW.tuan, NEW.nam
        USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

-- 3b) Cột dây / lô không được chuyển sang phiếu khác (ô lưới sẽ trỏ chéo phiếu).
CREATE OR REPLACE FUNCTION public.fn_dgdv_trg_chan_doi_phieu()
    RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'public'
    AS $$
BEGIN
  IF NEW.id_phieu IS DISTINCT FROM OLD.id_phieu THEN
    RAISE EXCEPTION 'Không được chuyển % sang phiếu khác', TG_TABLE_NAME USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;

-- 3c) Đứt dây / ô lưới: ngày phải thuộc tuần ISO của phiếu; ô lưới: cột dây cùng phiếu với lô.
CREATE OR REPLACE FUNCTION public.fn_dgdv_trg_kiem_ngay()
    RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  v_phieu bigint;
  v_dau date;
BEGIN
  SELECT p.id, public.fn_dgdv_ngay_dau_tuan(p.nam, p.tuan)
    INTO v_phieu, v_dau
  FROM public.fp_farm_dgdv_lo l
  JOIN public.fp_farm_dgdv p ON p.id = l.id_phieu
  WHERE l.id = NEW.id_phieu_lo;

  IF v_phieu IS NULL THEN
    RETURN NEW; -- FK sẽ báo lỗi lô không tồn tại
  END IF;

  IF NEW.ngay NOT BETWEEN v_dau AND v_dau + 6 THEN
    RAISE EXCEPTION 'Ngày % không thuộc tuần của phiếu (% – %)',
      to_char(NEW.ngay, 'DD/MM/YYYY'), to_char(v_dau, 'DD/MM/YYYY'), to_char(v_dau + 6, 'DD/MM/YYYY')
      USING ERRCODE = '23514';
  END IF;

  -- IF lồng: NEW.id_cot chỉ được đụng tới khi chạy trên _dong (_lo_ngay không có cột này).
  IF TG_TABLE_NAME = 'fp_farm_dgdv_dong' THEN
    IF NOT EXISTS (SELECT 1 FROM public.fp_farm_dgdv_cot c WHERE c.id = NEW.id_cot AND c.id_phieu = v_phieu) THEN
      RAISE EXCEPTION 'Cột dây % không thuộc phiếu của lô', NEW.id_cot USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.fn_dgdv_trg_kiem_phieu() FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.fn_dgdv_trg_chan_doi_phieu() FROM PUBLIC, anon;
