-- Số hoá file Excel «KIỂM TRA ĐÁNH GIÁ ĐẦU VÀO»: 1 phiếu / tuần ISO / chi nhánh, lưới ngang
-- (cột dây màu × lô × ngày). Khớp features/quan-ly-nha-so-che/danh-gia-dau-vao (làm ở đợt sau).
--
-- Phiếu này là NGUỒN DUY NHẤT của số buồng theo ngày + chi nhánh:
--   tong_thu = Σ fp_farm_dgdv_dong.so_luong + Σ fp_farm_dgdv_lo_ngay.dut_day
--   ksc      = Σ fp_farm_dgdv_dong.so_luong_loi
--   → fp_farm_bao_cao_so_che_ct  (ma_chi_tieu 'tong_buong_thu_hoach' = tong_thu,
--                                  'tong_buong_khong_so_che' = ksc)
--   → fp_farm_du_bao_sl_dong_thung.tong_buong_nhap_thuc_te = tong_thu (cột GENERATED tự tính lại)
-- Hai ô đích bị trigger BEFORE ghi đè mỗi lần INSERT/UPDATE → nhập tay không có tác dụng;
-- không có phiếu = 0. Đồng bộ ghi cả phiếu đích đã khoá (khoá trạng thái ở 2 module đích chỉ
-- nằm ở tầng app — DB không có trigger chặn UPDATE theo trang_thai, nên không cần cờ bỏ qua).
--
-- tong_buong_so_che / sl_buong_ton_cuoi_ngay: KHÔNG phải số suy ra — form Báo cáo sơ chế cho
-- nhập tay độc lập cả 5 chỉ tiêu (core/schema.ts, services/*-db.service.ts ctRowsFromForm),
-- không có công thức nào ở app hay DB → migration này không đụng tới.
--
-- !!! Cuối file có BACKFILL ghi đè TOÀN BỘ dữ liệu cũ của 2 ô đích (về 0 khi chưa có phiếu),
--     kể cả phiếu đã khoá. Giá trị cũ vẫn tra / khôi phục được ở fp_var_nhat_ky_thay_doi
--     (trigger nhật ký 016 ghi cột cũ / mới) và bản backup.
--
-- Chạy lại được nhiều lần (IF NOT EXISTS / CREATE OR REPLACE / ON CONFLICT DO NOTHING).
-- Trước khi chạy: bash scripts/db-backup.sh truoc-052
