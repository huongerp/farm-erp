BEGIN;

-- 0) Tiện ích tuần ISO ----------------------------------------------------------
-- Thứ Hai của tuần ISO (nam, tuan): thứ Hai của tuần chứa ngày 04/01 + (tuan - 1) tuần.
CREATE OR REPLACE FUNCTION public.fn_dgdv_ngay_dau_tuan(p_nam integer, p_tuan integer)
    RETURNS date
    LANGUAGE sql IMMUTABLE
    SET search_path TO 'public'
    AS $$
  SELECT make_date(p_nam, 1, 4)
         - (extract(isodow FROM make_date(p_nam, 1, 4))::integer - 1)
         + (p_tuan - 1) * 7;
$$;

COMMENT ON FUNCTION public.fn_dgdv_ngay_dau_tuan(integer, integer) IS
  'Ngày thứ Hai của tuần ISO (nam, tuan) — dùng cho phiếu Đánh giá đầu vào';

REVOKE ALL ON FUNCTION public.fn_dgdv_ngay_dau_tuan(integer, integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_dgdv_ngay_dau_tuan(integer, integer) TO authenticated;

