-- 2) Phiếu (mỗi phiếu = 1 cây hàng) ---------------------------------------------
CREATE TABLE public.fp_farm_giam_sat_chat_luong (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    so_phieu text UNIQUE,
    ngay date DEFAULT CURRENT_DATE NOT NULL,
    id_chi_nhanh bigint NOT NULL REFERENCES public.fp_var_chi_nhanh(id) ON DELETE RESTRICT,
    id_hang_hoa bigint REFERENCES public.fp_mh_danh_sach_hang_hoa(id) ON DELETE RESTRICT,
    ma_cay_hang text,
    so_thung_cay integer DEFAULT 60 NOT NULL,
    so_thung_mau integer DEFAULT 10 NOT NULL,
    tieu_chi jsonb DEFAULT '[]'::jsonb NOT NULL,
    trang_thai text DEFAULT 'dang_kiem'::text NOT NULL,
    ket_luan text,
    ghi_chu text,
    id_nguoi_tao bigint REFERENCES public.fp_var_nhan_vien(id) ON DELETE SET NULL,
    tg_tao timestamp with time zone DEFAULT now() NOT NULL,
    tg_cap_nhat timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT fp_farm_gscl_so_thung_check
      CHECK (so_thung_cay > 0 AND so_thung_mau BETWEEN 1 AND 100 AND so_thung_mau <= so_thung_cay),
    CONSTRAINT fp_farm_gscl_trang_thai_check
      CHECK (trang_thai = ANY (ARRAY['dang_kiem'::text, 'hoan_thanh'::text, 'huy'::text])),
    CONSTRAINT fp_farm_gscl_ket_luan_check
      CHECK (ket_luan IS NULL OR ket_luan = ANY (ARRAY['dat'::text, 'khong_dat'::text]))
);

COMMENT ON TABLE public.fp_farm_giam_sat_chat_luong IS 'Phiếu giám sát chất lượng: mỗi phiếu là một cây hàng, kiểm N thùng mẫu';
