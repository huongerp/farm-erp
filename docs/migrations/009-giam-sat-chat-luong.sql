COMMENT ON COLUMN public.fp_farm_giam_sat_chat_luong.tieu_chi IS 'Ảnh chụp bộ tiêu chí + ngưỡng lúc tạo phiếu (sửa danh mục không làm sai phiếu cũ)';
COMMENT ON COLUMN public.fp_farm_giam_sat_chat_luong.ket_luan IS 'dat | khong_dat — app tính theo ngưỡng khi đủ thùng mẫu';

