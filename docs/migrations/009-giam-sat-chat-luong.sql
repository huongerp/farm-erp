-- Số phiếu + ảnh chụp tiêu chí khi tạo.
CREATE FUNCTION public.fn_farm_gscl_truoc_khi_tao() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
  IF NEW.so_phieu IS NULL OR btrim(NEW.so_phieu) = '' THEN
    NEW.so_phieu := 'GS-' || lpad(NEW.id::text, 5, '0');
  END IF;
  IF NEW.tieu_chi IS NULL OR NEW.tieu_chi = '[]'::jsonb THEN
    SELECT COALESCE(jsonb_agg(jsonb_build_object(
             'ma', tc.ma, 'ten', tc.ten, 'loai', tc.loai, 'don_vi', tc.don_vi,
             'nguong_min', tc.nguong_min, 'nguong_max', tc.nguong_max
           ) ORDER BY tc.thu_tu, tc.id), '[]'::jsonb)
      INTO NEW.tieu_chi
      FROM public.fp_farm_gscl_tieu_chi tc
     WHERE tc.dang_dung;
  END IF;
  RETURN NEW;
END
$$;

CREATE TRIGGER trg_farm_gscl_truoc_khi_tao BEFORE INSERT ON public.fp_farm_giam_sat_chat_luong
  FOR EACH ROW EXECUTE FUNCTION public.fn_farm_gscl_truoc_khi_tao();

-- 3) Thùng mẫu (mỗi thùng 1 dòng, 1 tem) ------------------------------------------
CREATE TABLE public.fp_farm_giam_sat_chat_luong_ct (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_phieu bigint NOT NULL REFERENCES public.fp_farm_giam_sat_chat_luong(id) ON DELETE CASCADE,
    stt_thung integer NOT NULL,
    ma_tem text NOT NULL UNIQUE,
    ket_qua jsonb DEFAULT '{}'::jsonb NOT NULL,
    da_kiem boolean DEFAULT false NOT NULL,
    tg_kiem timestamp with time zone,
    id_nguoi_kiem bigint REFERENCES public.fp_var_nhan_vien(id) ON DELETE SET NULL,
    ghi_chu text,
    CONSTRAINT fp_farm_gscl_ct_stt_check CHECK (stt_thung >= 1),
    CONSTRAINT fp_farm_gscl_ct_phieu_stt_key UNIQUE (id_phieu, stt_thung)
);

COMMENT ON TABLE public.fp_farm_giam_sat_chat_luong_ct IS 'Thùng mẫu của phiếu giám sát chất lượng — sinh sẵn theo so_thung_mau';
COMMENT ON COLUMN public.fp_farm_giam_sat_chat_luong_ct.ma_tem IS 'Nội dung QR trên tem: <so_phieu>-<stt> (app thêm tiền tố GSCL:)';
COMMENT ON COLUMN public.fp_farm_giam_sat_chat_luong_ct.ket_qua IS '{ma_tieu_chi: số | true/false}';

-- Sinh / cắt dòng thùng theo so_thung_mau. Không cho cắt thùng đã kiểm.
CREATE FUNCTION public.fn_farm_gscl_dong_bo_thung() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM public.fp_farm_giam_sat_chat_luong_ct
     WHERE id_phieu = NEW.id AND stt_thung > NEW.so_thung_mau AND da_kiem
  ) THEN
    RAISE EXCEPTION 'Không giảm số thùng mẫu xuống % được: đã có thùng số lớn hơn được kiểm', NEW.so_thung_mau
      USING ERRCODE = 'P0001';
  END IF;

  DELETE FROM public.fp_farm_giam_sat_chat_luong_ct
   WHERE id_phieu = NEW.id AND stt_thung > NEW.so_thung_mau;

  INSERT INTO public.fp_farm_giam_sat_chat_luong_ct (id_phieu, stt_thung, ma_tem)
  SELECT NEW.id, g, NEW.so_phieu || '-' || lpad(g::text, 2, '0')
    FROM generate_series(1, NEW.so_thung_mau) AS g
  ON CONFLICT (id_phieu, stt_thung) DO NOTHING;

  RETURN NULL;
END
$$;

CREATE TRIGGER trg_farm_gscl_dong_bo_thung
  AFTER INSERT OR UPDATE OF so_thung_mau ON public.fp_farm_giam_sat_chat_luong
  FOR EACH ROW EXECUTE FUNCTION public.fn_farm_gscl_dong_bo_thung();

CREATE INDEX idx_fp_farm_gscl_ct_phieu ON public.fp_farm_giam_sat_chat_luong_ct USING btree (id_phieu);

