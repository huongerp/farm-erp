-- 089-bcnc-chot-thuong-thang.sql — Báo cáo nhân công: chốt thưởng vượt thùng theo tháng
--
-- Thưởng vượt thùng (087) tính sống trên app từ phiếu × cài đặt hệ số × Ki → sửa phiếu ngày cũ,
-- đổi Ki hay đổi hệ số là số tháng đã trả đổi theo. Chốt tháng:
--   1. fp_farm_bcnc_chot_thang    — đầu: nhà sơ chế + tháng đã chốt, ai chốt, tổng tiền, đơn giá/ngưỡng lúc chốt
--   2. fp_farm_bcnc_chot_thang_ct — ảnh chụp số tiền từng công nhân (kèm chi tiết từng ngày, jsonb)
--   3. rpc_bcnc_chot_thang / rpc_bcnc_mo_chot_thang — chỉ ghi qua RPC (duyệt/quản trị chốt, quản trị mở)
--   4. Trigger chặn sửa phiếu (đầu + bảng con) và Ki của tháng đã chốt — kể cả cấp cao: muốn sửa
--      phải mở chốt trước để số đã chi luôn khớp ảnh chụp. Cài đặt hệ số không chặn: tháng đã chốt
--      đọc từ ảnh chụp.
-- Migration, SQL tay, hàm SECURITY DEFINER (current_user <> 'authenticated') không bị chặn.
--
-- Chạy: bash scripts/db-sql.sh -v ON_ERROR_STOP=1 -f docs/migrations/089-bcnc-chot-thuong-thang.sql
-- =============================================================================
BEGIN;

-- 1) Đầu chốt.
CREATE TABLE IF NOT EXISTS public.fp_farm_bcnc_chot_thang (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chi_nhanh bigint NOT NULL REFERENCES public.fp_var_chi_nhanh(id) ON DELETE CASCADE,
    thang date NOT NULL,
    so_nguoi integer DEFAULT 0 NOT NULL,
    tong_tien numeric(14,0) DEFAULT 0 NOT NULL,
    don_gia_vuot numeric(12,2),
    nguong_ns_pct numeric(5,2),
    nguoi_chot bigint REFERENCES public.fp_var_nhan_vien(id) ON DELETE SET NULL,
    tg_chot timestamp with time zone DEFAULT now() NOT NULL,
    ghi_chu text,
    CONSTRAINT fp_farm_bcnc_ct_thang_chk CHECK (thang = date_trunc('month', thang)::date)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_fp_farm_bcnc_chot_thang
  ON public.fp_farm_bcnc_chot_thang (id_chi_nhanh, thang);
COMMENT ON TABLE public.fp_farm_bcnc_chot_thang IS
  'Báo cáo nhân công — tháng đã chốt thưởng vượt thùng của một nhà sơ chế; có dòng = phiếu + Ki tháng đó bị khoá';

-- 2) Ảnh chụp từng công nhân.
CREATE TABLE IF NOT EXISTS public.fp_farm_bcnc_chot_thang_ct (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chot bigint NOT NULL REFERENCES public.fp_farm_bcnc_chot_thang(id) ON DELETE CASCADE,
    thu_tu integer DEFAULT 0 NOT NULL,
    khoa_nv text NOT NULL,
    id_nhan_vien bigint REFERENCES public.fp_var_nhan_vien_so_che(id) ON DELETE SET NULL,
    ho_ten text NOT NULL,
    vi_tri text,
    chuyen text[] DEFAULT '{}'::text[] NOT NULL,
    so_ngay integer DEFAULT 0 NOT NULL,
    gio_cong numeric(10,2) DEFAULT 0 NOT NULL,
    thung_vuot numeric(12,2) DEFAULT 0 NOT NULL,
    tien_truoc_ki numeric(14,0) DEFAULT 0 NOT NULL,
    ki numeric(4,2) DEFAULT 1 NOT NULL,
    tien numeric(14,0) DEFAULT 0 NOT NULL,
    chi_tiet_ngay jsonb DEFAULT '[]'::jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_fp_farm_bcnc_chot_thang_ct_chot
  ON public.fp_farm_bcnc_chot_thang_ct (id_chot, thu_tu);
COMMENT ON TABLE public.fp_farm_bcnc_chot_thang_ct IS
  'Ảnh chụp thưởng vượt thùng tháng của từng công nhân lúc chốt (chi_tiet_ngay: [{ngay, loai_chuyen, soNhom, gioCong, thungVuotQuyDoi, tien}])';

-- 3) RLS: ai xem module thì đọc; ghi chỉ qua RPC (không có policy ghi, không GRANT ghi).
DO $$
DECLARE
  c_mod constant text := 'quan-ly-nha-so-che/bao-cao-nhan-cong';
  c_xem constant text := 'ARRAY[''view'', ''create'', ''update'', ''delete'', ''approve'', ''admin'', ''all'']';
  r record;
BEGIN
  FOR r IN
    SELECT * FROM (VALUES
      ('fp_farm_bcnc_chot_thang', 'fp_farm_bcnc_chot'),
      ('fp_farm_bcnc_chot_thang_ct', 'fp_farm_bcnc_chot_ct')
    ) AS t(bang, ten)
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_select_quyen', r.bang);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_select_quyen', r.bang, c_mod, c_xem);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon, authenticated', r.bang);
    EXECUTE format('GRANT SELECT ON TABLE public.%I TO authenticated', r.bang);
    EXECUTE format('REVOKE ALL ON SEQUENCE public.%I FROM PUBLIC, anon', r.bang || '_id_seq');
    -- Nhật ký thay đổi (migration 016): mở chốt nhầm vẫn khôi phục được ảnh chụp từ nhật ký.
    EXECUTE format('CREATE OR REPLACE TRIGGER trg_nhat_ky_thay_doi AFTER INSERT OR UPDATE OR DELETE ON public.%I '
                   'FOR EACH ROW EXECUTE FUNCTION public.fn_ghi_nhat_ky_thay_doi()', r.bang);
  END LOOP;
END;
$$;

-- 4) Tra tháng đã chốt.
CREATE OR REPLACE FUNCTION public.fn_bcnc_thang_da_chot(p_id_chi_nhanh bigint, p_ngay date) RETURNS boolean
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
  SELECT p_id_chi_nhanh IS NOT NULL AND p_ngay IS NOT NULL AND EXISTS (
    SELECT 1 FROM public.fp_farm_bcnc_chot_thang c
    WHERE c.id_chi_nhanh = p_id_chi_nhanh AND c.thang = date_trunc('month', p_ngay)::date
  );
$$;
REVOKE ALL ON FUNCTION public.fn_bcnc_thang_da_chot(bigint, date) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_bcnc_thang_da_chot(bigint, date) TO authenticated;

-- 5) Trigger chặn sửa dữ liệu của tháng đã chốt.
CREATE OR REPLACE FUNCTION public.fn_bcnc_chan_thang_da_chot() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'public'
    AS $$
DECLARE
  v_cn bigint;
  v_ngay date;
  v_cn_moi bigint;
  v_ngay_moi date;
BEGIN
  -- Migration, SQL tay, hàm SECURITY DEFINER: không chặn.
  IF current_user <> 'authenticated' THEN
    RETURN COALESCE(NEW, OLD);
  END IF;

  IF TG_TABLE_NAME = 'fp_farm_bao_cao_nhan_cong' THEN
    IF TG_OP <> 'INSERT' THEN v_cn := OLD.id_chi_nhanh; v_ngay := OLD.ngay; END IF;
    IF TG_OP <> 'DELETE' THEN v_cn_moi := NEW.id_chi_nhanh; v_ngay_moi := NEW.ngay; END IF;
  ELSIF TG_TABLE_NAME = 'fp_farm_bcnc_he_so_loi_thang' THEN
    IF TG_OP <> 'INSERT' THEN v_cn := OLD.id_chi_nhanh; v_ngay := OLD.thang; END IF;
    IF TG_OP <> 'DELETE' THEN v_cn_moi := NEW.id_chi_nhanh; v_ngay_moi := NEW.thang; END IF;
  ELSIF TG_TABLE_NAME = 'fp_farm_bao_cao_nhan_cong_ct' THEN
    -- Bảng con: tra phiếu cha (xoá dây chuyền khi cha đã mất → không thấy cha → cho qua, cha đã bị chặn ở trên).
    IF TG_OP <> 'INSERT' THEN
      SELECT p.id_chi_nhanh, p.ngay INTO v_cn, v_ngay FROM public.fp_farm_bao_cao_nhan_cong p WHERE p.id = OLD.id_bao_cao;
    END IF;
    IF TG_OP <> 'DELETE' THEN
      SELECT p.id_chi_nhanh, p.ngay INTO v_cn_moi, v_ngay_moi FROM public.fp_farm_bao_cao_nhan_cong p WHERE p.id = NEW.id_bao_cao;
    END IF;
  ELSE
    -- fp_farm_bao_cao_nhan_cong_nv / _ct_sub: qua dòng chuyền.
    IF TG_OP <> 'INSERT' THEN
      SELECT p.id_chi_nhanh, p.ngay INTO v_cn, v_ngay
        FROM public.fp_farm_bao_cao_nhan_cong_ct ct
        JOIN public.fp_farm_bao_cao_nhan_cong p ON p.id = ct.id_bao_cao
       WHERE ct.id = OLD.id_bcnc_ct;
    END IF;
    IF TG_OP <> 'DELETE' THEN
      SELECT p.id_chi_nhanh, p.ngay INTO v_cn_moi, v_ngay_moi
        FROM public.fp_farm_bao_cao_nhan_cong_ct ct
        JOIN public.fp_farm_bao_cao_nhan_cong p ON p.id = ct.id_bao_cao
       WHERE ct.id = NEW.id_bcnc_ct;
    END IF;
  END IF;

  IF public.fn_bcnc_thang_da_chot(v_cn, v_ngay) THEN
    RAISE EXCEPTION 'Tháng % của nhà sơ chế đã chốt thưởng — nhờ quản trị mở chốt trước khi sửa.', to_char(v_ngay, 'MM/YYYY')
      USING ERRCODE = 'P0001';
  END IF;
  IF public.fn_bcnc_thang_da_chot(v_cn_moi, v_ngay_moi) THEN
    RAISE EXCEPTION 'Tháng % của nhà sơ chế đã chốt thưởng — nhờ quản trị mở chốt trước khi sửa.', to_char(v_ngay_moi, 'MM/YYYY')
      USING ERRCODE = 'P0001';
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;

DO $$
DECLARE
  b text;
BEGIN
  FOREACH b IN ARRAY ARRAY[
    'fp_farm_bao_cao_nhan_cong',
    'fp_farm_bao_cao_nhan_cong_ct',
    'fp_farm_bao_cao_nhan_cong_ct_sub',
    'fp_farm_bao_cao_nhan_cong_nv',
    'fp_farm_bcnc_he_so_loi_thang'
  ] LOOP
    EXECUTE format('CREATE OR REPLACE TRIGGER trg_bcnc_chan_thang_da_chot BEFORE INSERT OR UPDATE OR DELETE ON public.%I '
                   'FOR EACH ROW EXECUTE FUNCTION public.fn_bcnc_chan_thang_da_chot()', b);
  END LOOP;
END;
$$;

-- 6) RPC chốt: duyệt / quản trị (fn_co_quyen_module đã gồm cấp bậc 1, chức vụ tt = 1, super admin).
CREATE OR REPLACE FUNCTION public.rpc_bcnc_chot_thang(
  p_id_chi_nhanh bigint,
  p_thang date,
  p_don_gia numeric,
  p_nguong_pct numeric,
  p_dong jsonb
) RETURNS bigint
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  v_thang date := date_trunc('month', p_thang)::date;
  v_id bigint;
BEGIN
  IF NOT public.fn_co_quyen_module('quan-ly-nha-so-che/bao-cao-nhan-cong', ARRAY['approve', 'admin', 'all']) THEN
    RAISE EXCEPTION 'Chỉ người có quyền duyệt hoặc quản trị Báo cáo nhân công mới chốt thưởng tháng.' USING ERRCODE = 'P0001';
  END IF;
  IF p_dong IS NULL OR jsonb_typeof(p_dong) <> 'array' OR jsonb_array_length(p_dong) = 0 THEN
    RAISE EXCEPTION 'Tháng % chưa có công nhân nào để chốt.', to_char(v_thang, 'MM/YYYY') USING ERRCODE = 'P0001';
  END IF;
  IF EXISTS (SELECT 1 FROM public.fp_farm_bcnc_chot_thang WHERE id_chi_nhanh = p_id_chi_nhanh AND thang = v_thang) THEN
    RAISE EXCEPTION 'Tháng % của nhà sơ chế này đã chốt rồi.', to_char(v_thang, 'MM/YYYY') USING ERRCODE = 'P0001';
  END IF;

  INSERT INTO public.fp_farm_bcnc_chot_thang (id_chi_nhanh, thang, don_gia_vuot, nguong_ns_pct, nguoi_chot)
  VALUES (p_id_chi_nhanh, v_thang, p_don_gia, p_nguong_pct, public.nhan_vien_hien_tai_id())
  RETURNING id INTO v_id;

  INSERT INTO public.fp_farm_bcnc_chot_thang_ct
    (id_chot, thu_tu, khoa_nv, id_nhan_vien, ho_ten, vi_tri, chuyen, so_ngay, gio_cong, thung_vuot, tien_truoc_ki, ki, tien, chi_tiet_ngay)
  SELECT
    v_id,
    d.ord::integer,
    d.v ->> 'khoa_nv',
    NULLIF(d.v ->> 'id_nhan_vien', '')::bigint,
    d.v ->> 'ho_ten',
    NULLIF(d.v ->> 'vi_tri', ''),
    COALESCE(ARRAY(SELECT jsonb_array_elements_text(d.v -> 'chuyen')), '{}'::text[]),
    COALESCE((d.v ->> 'so_ngay')::integer, 0),
    COALESCE((d.v ->> 'gio_cong')::numeric, 0),
    COALESCE((d.v ->> 'thung_vuot')::numeric, 0),
    COALESCE((d.v ->> 'tien_truoc_ki')::numeric, 0),
    COALESCE((d.v ->> 'ki')::numeric, 1),
    COALESCE((d.v ->> 'tien')::numeric, 0),
    COALESCE(d.v -> 'chi_tiet_ngay', '[]'::jsonb)
  FROM jsonb_array_elements(p_dong) WITH ORDINALITY AS d(v, ord);

  UPDATE public.fp_farm_bcnc_chot_thang c
     SET so_nguoi = s.n, tong_tien = s.tong
    FROM (SELECT count(*) AS n, COALESCE(sum(tien), 0) AS tong FROM public.fp_farm_bcnc_chot_thang_ct WHERE id_chot = v_id) s
   WHERE c.id = v_id;

  RETURN v_id;
END;
$$;
REVOKE ALL ON FUNCTION public.rpc_bcnc_chot_thang(bigint, date, numeric, numeric, jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rpc_bcnc_chot_thang(bigint, date, numeric, numeric, jsonb) TO authenticated;

-- 7) RPC mở chốt: chỉ quản trị (admin/all trên module hoặc cấp cao).
CREATE OR REPLACE FUNCTION public.rpc_bcnc_mo_chot_thang(p_id_chi_nhanh bigint, p_thang date) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  v_thang date := date_trunc('month', p_thang)::date;
BEGIN
  IF NOT public.fn_co_quyen_module('quan-ly-nha-so-che/bao-cao-nhan-cong', ARRAY['admin', 'all']) THEN
    RAISE EXCEPTION 'Chỉ quản trị Báo cáo nhân công mới mở chốt thưởng tháng.' USING ERRCODE = 'P0001';
  END IF;
  -- Xoá dòng con trước để nhật ký ghi lại từng người (cascade không qua trigger nhật ký của bảng con).
  DELETE FROM public.fp_farm_bcnc_chot_thang_ct ct
   USING public.fp_farm_bcnc_chot_thang c
   WHERE ct.id_chot = c.id AND c.id_chi_nhanh = p_id_chi_nhanh AND c.thang = v_thang;
  DELETE FROM public.fp_farm_bcnc_chot_thang WHERE id_chi_nhanh = p_id_chi_nhanh AND thang = v_thang;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Tháng % của nhà sơ chế này chưa chốt.', to_char(v_thang, 'MM/YYYY') USING ERRCODE = 'P0001';
  END IF;
END;
$$;
REVOKE ALL ON FUNCTION public.rpc_bcnc_mo_chot_thang(bigint, date) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rpc_bcnc_mo_chot_thang(bigint, date) TO authenticated;

COMMIT;

