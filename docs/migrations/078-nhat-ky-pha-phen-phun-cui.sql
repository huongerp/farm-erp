-- 1) Hồ phèn theo NSC (cài đặt định mức) ----------------------------------------
-- Đầu ca (lần 1) mỗi hồ = (xắn + tỉa) m³ × ty_le_g_lit (g/lít = kg/m³) × ty_le_dau_ca.
-- Bổ sung (kg) xắn + tỉa chia đều các lần sau (9h-11h-15h-17h). Khớp core/dinh-muc.ts.
CREATE TABLE IF NOT EXISTS public.fp_farm_pp_ho (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chi_nhanh bigint NOT NULL REFERENCES public.fp_var_chi_nhanh(id) ON DELETE RESTRICT,
    ten_ho text NOT NULL,
    the_tich_xan_m3 numeric(10,3),
    the_tich_tia_m3 numeric(10,3),
    bo_sung_xan_kg numeric(10,3),
    bo_sung_tia_kg numeric(10,3),
    ty_le_g_lit numeric(10,4) DEFAULT 0.5 NOT NULL,
    ty_le_dau_ca numeric(5,4) DEFAULT 0.8 NOT NULL,
    dang_dung boolean DEFAULT true NOT NULL,
    thu_tu integer DEFAULT 0 NOT NULL,
    ghi_chu text,
    id_nguoi_tao bigint DEFAULT public.nhan_vien_hien_tai_id()
      REFERENCES public.fp_var_nhan_vien(id) ON DELETE SET NULL,
    tg_tao timestamp with time zone DEFAULT now() NOT NULL,
    tg_cap_nhat timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT fp_farm_pp_ho_cn_ten_key UNIQUE (id_chi_nhanh, ten_ho),
    CONSTRAINT fp_farm_pp_ho_ten_check CHECK (btrim(ten_ho) <> ''),
    CONSTRAINT fp_farm_pp_ho_so_check CHECK (
      COALESCE(the_tich_xan_m3, 0) >= 0 AND COALESCE(the_tich_tia_m3, 0) >= 0
      AND COALESCE(bo_sung_xan_kg, 0) >= 0 AND COALESCE(bo_sung_tia_kg, 0) >= 0
      AND ty_le_g_lit >= 0 AND ty_le_dau_ca BETWEEN 0 AND 1)
);

COMMENT ON TABLE public.fp_farm_pp_ho IS 'Hồ pha phèn của từng NSC (hồ xắn + hồ tỉa) — căn cứ tính định mức phèn';
COMMENT ON COLUMN public.fp_farm_pp_ho.ty_le_g_lit IS 'Tỷ lệ pha g phèn / lít nước (= kg/m³), mặc định 0,5';
COMMENT ON COLUMN public.fp_farm_pp_ho.ty_le_dau_ca IS 'Phần lượng phèn theo thể tích dùng ở lần đầu ca (7h), mặc định 0,8';
COMMENT ON COLUMN public.fp_farm_pp_ho.bo_sung_xan_kg IS 'Kg phèn bổ sung hồ xắn trong ngày, chia đều các lần sau đầu ca';

-- 2) Nhật ký pha phèn: 1 ngày / 1 NSC ---------------------------------------------
CREATE TABLE IF NOT EXISTS public.fp_farm_pp_nhat_ky (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ngay date NOT NULL,
    id_chi_nhanh bigint NOT NULL REFERENCES public.fp_var_chi_nhanh(id) ON DELETE RESTRICT,
    so_buong_du_thu integer,
    so_be_so_che integer,
    id_nhan_vien_phu_trach bigint REFERENCES public.fp_var_nhan_vien(id) ON DELETE SET NULL,
    ghi_chu text,
    id_nguoi_tao bigint DEFAULT public.nhan_vien_hien_tai_id()
      REFERENCES public.fp_var_nhan_vien(id) ON DELETE SET NULL,
    tg_tao timestamp with time zone DEFAULT now() NOT NULL,
    tg_cap_nhat timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT fp_farm_pp_nhat_ky_cn_ngay_key UNIQUE (id_chi_nhanh, ngay),
    CONSTRAINT fp_farm_pp_nhat_ky_so_check
      CHECK (COALESCE(so_buong_du_thu, 0) >= 0 AND COALESCE(so_be_so_che, 0) >= 0)
);

COMMENT ON TABLE public.fp_farm_pp_nhat_ky IS 'Nhật ký pha phèn theo ngày của từng NSC';

CREATE INDEX IF NOT EXISTS idx_fp_farm_pp_nhat_ky_ngay ON public.fp_farm_pp_nhat_ky USING btree (ngay DESC);

-- 3) Các lần pha phèn trong ngày (lần 1..5: 7h, 9h, 11h, 15h, 17h) ------------------
CREATE TABLE IF NOT EXISTS public.fp_farm_pp_nhat_ky_lan (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_nhat_ky bigint NOT NULL REFERENCES public.fp_farm_pp_nhat_ky(id) ON DELETE CASCADE,
    lan smallint NOT NULL,
    gio time without time zone,
    so_kg numeric(10,3),
    dinh_muc_kg numeric(10,3),
    CONSTRAINT fp_farm_pp_nhat_ky_lan_key UNIQUE (id_nhat_ky, lan),
    CONSTRAINT fp_farm_pp_nhat_ky_lan_check CHECK (lan BETWEEN 1 AND 5),
    CONSTRAINT fp_farm_pp_nhat_ky_lan_so_check
      CHECK (COALESCE(so_kg, 0) >= 0 AND COALESCE(dinh_muc_kg, 0) >= 0)
);

COMMENT ON TABLE public.fp_farm_pp_nhat_ky_lan IS 'Lần pha phèn trong ngày: số kg thực tế + định mức chụp lúc lưu';
COMMENT ON COLUMN public.fp_farm_pp_nhat_ky_lan.dinh_muc_kg IS 'Định mức kg của lần pha, chụp từ cài đặt hồ lúc lưu (đổi cài đặt sau không làm sai nhật ký cũ)';

