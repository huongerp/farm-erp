-- 094-dgdv-nhom-loi.sql — Đánh giá đầu vào: nhóm nguyên nhân lỗi + view gom lỗi theo ngày
--
-- Mục tiêu: báo cáo tỷ lệ lỗi theo nhóm (Thu hoạch / Chăm sóc vườn / Chăm sóc buồng).
--   1. fp_var_dgdv_nhom_loi — danh mục nhóm nguyên nhân lỗi (tên, mã màu, thứ tự, đang dùng).
--      Seed 3 nhóm; thêm/sửa trong dialog Cài đặt ⚙ của module.
--   2. fp_var_dgdv_ly_do.id_nhom_loi — mỗi lý do chọn nhanh gắn 1 nhóm (NULL = chưa gán, người dùng
--      tự gán trong Cài đặt). Migration gán sẵn các lý do đã có theo tên, chỉ gán khi còn NULL.
--   3. v_fp_farm_dgdv_loi_ngay — gom số buồng lỗi theo ngày × chi nhánh × lô × tên lỗi, gồm cả
--      đánh giá (danh_gia) lẫn lý do huỷ (ly_do_huy). App join tên → id_nhom_loi để ra tỷ lệ theo nhóm.
--
-- RLS + GRANT + trigger nhật ký theo khuôn migration 052 mục 7 (bảng danh mục: đọc = mọi quyền
-- trên module, ghi = admin/all).
--
-- Chạy: bash scripts/db-sql.sh -v ON_ERROR_STOP=1 -f docs/migrations/094-dgdv-nhom-loi.sql
-- Chạy lại được nhiều lần: IF NOT EXISTS / ON CONFLICT DO NOTHING / CREATE OR REPLACE / chỉ gán khi NULL.
-- =============================================================================

BEGIN;

-- 1) Danh mục nhóm nguyên nhân lỗi ------------------------------------------------
CREATE TABLE IF NOT EXISTS public.fp_var_dgdv_nhom_loi (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten text NOT NULL,
    ma_mau text NOT NULL,
    thu_tu integer DEFAULT 0 NOT NULL,
    dang_dung boolean DEFAULT true NOT NULL,
    tg_tao timestamp with time zone DEFAULT now() NOT NULL,
    tg_cap_nhat timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT fp_var_dgdv_nhom_loi_ten_check CHECK (btrim(ten) <> ''),
    CONSTRAINT fp_var_dgdv_nhom_loi_ma_mau_check CHECK (ma_mau ~ '^#[0-9A-F]{6}$'),
    CONSTRAINT fp_var_dgdv_nhom_loi_ten_key UNIQUE (ten)
);

COMMENT ON TABLE public.fp_var_dgdv_nhom_loi IS
  'Đánh giá đầu vào — nhóm nguyên nhân lỗi (Thu hoạch / Chăm sóc vườn / Chăm sóc buồng) để báo cáo tỷ lệ lỗi theo nhóm';
COMMENT ON COLUMN public.fp_var_dgdv_nhom_loi.ten IS 'Tên nhóm, duy nhất';
COMMENT ON COLUMN public.fp_var_dgdv_nhom_loi.ma_mau IS 'Màu hiển thị chip/badge, dạng #RRGGBB (chữ hoa)';
COMMENT ON COLUMN public.fp_var_dgdv_nhom_loi.thu_tu IS 'Thứ tự hiện trong danh sách (nhỏ trước)';
COMMENT ON COLUMN public.fp_var_dgdv_nhom_loi.dang_dung IS 'false = ẩn khỏi ô chọn, không xoá dữ liệu đã gán';

-- Seed 3 nhóm gốc; chạy lại không ghi đè tên/màu người dùng đã sửa.
INSERT INTO public.fp_var_dgdv_nhom_loi (ten, ma_mau, thu_tu)
VALUES
  ('Thu hoạch',       '#F59E0B', 1),
  ('Chăm sóc vườn',   '#10B981', 2),
  ('Chăm sóc buồng',  '#6366F1', 3)
ON CONFLICT (ten) DO NOTHING;

-- 2) Gắn nhóm cho lý do chọn nhanh -------------------------------------------------
ALTER TABLE public.fp_var_dgdv_ly_do
  ADD COLUMN IF NOT EXISTS id_nhom_loi bigint REFERENCES public.fp_var_dgdv_nhom_loi(id) ON DELETE SET NULL;

COMMENT ON COLUMN public.fp_var_dgdv_ly_do.id_nhom_loi IS
  'Nhóm nguyên nhân lỗi của lý do; NULL = chưa gán (người dùng gán trong Cài đặt)';

-- 3) Gán sẵn nhóm cho lý do đã có, khớp tên đã chuẩn hoá (thường, gọn 1 dấu cách).
--    Chỉ gán khi id_nhom_loi IS NULL → chạy lại không đè lựa chọn người dùng đã đổi.
UPDATE public.fp_var_dgdv_ly_do l
   SET id_nhom_loi = n.id
  FROM (VALUES
    -- Khớp NGUYÊN tên lý do (kể cả tên có dấu phẩy như «Trầy, dập tươi»), theo cột Excel của khách:
    -- LỖI THU HOẠCH = thiếu / quá kích thước, trầy mới / dập; LỖI CSV = nhọn đầu trái, rệp, côn trùng.
    ('thiếu size',          'Thu hoạch'),
    ('quá size',            'Thu hoạch'),
    ('quá size nải đầu',    'Thu hoạch'),
    ('quá size 2 nải đầu',  'Thu hoạch'),
    ('trầy, dập tươi',      'Thu hoạch'),
    ('trầy, dập mới nặng',  'Thu hoạch'),
    ('trầy tươi',           'Thu hoạch'),
    ('trầy tuoi',           'Thu hoạch'),
    ('dập trái',            'Thu hoạch'),
    ('dập cuống',           'Thu hoạch'),
    ('nhọn đầu trái',       'Chăm sóc vườn'),
    ('nhọn đầu',            'Chăm sóc vườn'),
    ('nhọn trái',           'Chăm sóc vườn'),
    ('rệp sáp',             'Chăm sóc vườn'),
    ('rệp sáp nặng',        'Chăm sóc vườn'),
    ('rệp vảy',             'Chăm sóc vườn'),
    ('rệp sáp, rệp vảy',    'Chăm sóc vườn'),
    ('côn trùng',           'Chăm sóc vườn'),
    ('côn trùng, sâu bọ',   'Chăm sóc vườn')
  ) AS t(khoa, ten_nhom)
  JOIN public.fp_var_dgdv_nhom_loi n ON n.ten = t.ten_nhom
 WHERE lower(regexp_replace(btrim(l.ten), '\s+', ' ', 'g')) = t.khoa
   AND l.id_nhom_loi IS NULL;

-- 4) Cập nhật tg_cap_nhat tự động ---------------------------------------------------
CREATE OR REPLACE TRIGGER trg_update_tg_cap_nhat BEFORE UPDATE ON public.fp_var_dgdv_nhom_loi
  FOR EACH ROW EXECUTE FUNCTION public.update_tg_cap_nhat_column();

-- 5) RLS + GRANT + nhật ký ----------------------------------------------------------
-- Đọc: có bất kỳ quyền nào trên module. Ghi danh mục: chỉ admin/all (như fp_var_dgdv_ly_do).
-- (SELECT fn(...)) để Postgres tính quyền một lần / câu lệnh.
DO $$
DECLARE
  c_mod constant text := 'quan-ly-nha-so-che/danh-gia-dau-vao';
  c_xem constant text := 'ARRAY[''view'', ''create'', ''update'', ''delete'', ''approve'', ''admin'', ''all'']';
  r record;
BEGIN
  FOR r IN
    SELECT * FROM (VALUES
      -- bảng, viết tắt policy, quyền INSERT, quyền UPDATE, quyền DELETE
      ('fp_var_dgdv_nhom_loi', 'fp_var_dgdv_nhom_loi', 'ARRAY[''admin'', ''all'']', 'ARRAY[''admin'', ''all'']', 'ARRAY[''admin'', ''all'']')
    ) AS t(bang, ten, q_ins, q_upd, q_del)
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', r.bang);

    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_select_quyen', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_insert_quyen', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_update_quyen', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_delete_quyen', r.bang);

    EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_select_quyen', r.bang, c_mod, c_xem);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR INSERT TO authenticated '
                   'WITH CHECK ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_insert_quyen', r.bang, c_mod, r.q_ins);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR UPDATE TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s))) '
                   'WITH CHECK ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_update_quyen', r.bang, c_mod, r.q_upd, c_mod, r.q_upd);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR DELETE TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_delete_quyen', r.bang, c_mod, r.q_del);

    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon', r.bang);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.%I TO authenticated', r.bang);
    EXECUTE format('REVOKE ALL ON SEQUENCE public.%I FROM PUBLIC, anon', r.bang || '_id_seq');
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE public.%I TO authenticated', r.bang || '_id_seq');

    -- Nhật ký thay đổi (migration 016) — tra ai đổi tên/màu nhóm.
    EXECUTE format('CREATE OR REPLACE TRIGGER trg_nhat_ky_thay_doi AFTER INSERT OR UPDATE OR DELETE ON public.%I '
                   'FOR EACH ROW EXECUTE FUNCTION public.fn_ghi_nhat_ky_thay_doi()', r.bang);
  END LOOP;
END $$;

-- 6) View gom số buồng lỗi theo ngày × chi nhánh × lô × tên lỗi -----------------------
-- 'danh_gia' = ô Đánh giá của dòng; 'huy' = lý do huỷ (KSC). App join ten → fp_var_dgdv_ly_do
-- → id_nhom_loi để cộng theo nhóm; tên không có trong danh mục để nhóm NULL.
CREATE OR REPLACE VIEW public.v_fp_farm_dgdv_loi_ngay
WITH (security_invoker = true) AS
WITH lo AS (
  SELECT l.id, l.id_lo, p.ngay, p.id_chi_nhanh
  FROM public.fp_farm_dgdv_lo l
  JOIN public.fp_farm_dgdv p ON p.id = l.id_phieu
)
SELECT lo.ngay, lo.id_chi_nhanh, lo.id_lo, 'danh_gia'::text AS loai,
       btrim(d.danh_gia) AS ten, SUM(d.so_luong)::bigint AS so_buong
FROM lo JOIN public.fp_farm_dgdv_dong d ON d.id_phieu_lo = lo.id
WHERE btrim(COALESCE(d.danh_gia, '')) <> ''
GROUP BY lo.ngay, lo.id_chi_nhanh, lo.id_lo, btrim(d.danh_gia)
HAVING SUM(d.so_luong) > 0
UNION ALL
SELECT lo.ngay, lo.id_chi_nhanh, lo.id_lo, 'huy'::text,
       btrim(d.ly_do_huy), SUM(d.so_luong_huy)::bigint
FROM lo JOIN public.fp_farm_dgdv_dong d ON d.id_phieu_lo = lo.id
WHERE d.so_luong_huy > 0 AND btrim(COALESCE(d.ly_do_huy, '')) <> ''
GROUP BY lo.ngay, lo.id_chi_nhanh, lo.id_lo, btrim(d.ly_do_huy);

COMMENT ON VIEW public.v_fp_farm_dgdv_loi_ngay IS
  'Đánh giá đầu vào — số buồng lỗi theo ngày × chi nhánh × lô × tên lỗi; '
  'loai = danh_gia (ô Đánh giá) | huy (lý do huỷ). Join ten → fp_var_dgdv_ly_do.id_nhom_loi để cộng theo nhóm';

REVOKE ALL ON TABLE public.v_fp_farm_dgdv_loi_ngay FROM PUBLIC, anon;
GRANT SELECT ON TABLE public.v_fp_farm_dgdv_loi_ngay TO authenticated;

COMMIT;

NOTIFY pgrst, 'reload schema';

