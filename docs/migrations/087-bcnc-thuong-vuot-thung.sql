-- =============================================================================
-- 087-bcnc-thuong-vuot-thung.sql — Báo cáo nhân công: thưởng vượt thùng cho công nhân
--
-- Yêu cầu NSC (chốt 20/11/2026): không chia đều thưởng nữa mà theo khâu khó/dễ.
--   Thùng vượt nhóm = max(0, số thùng − ngưỡng% × mục tiêu × giờ công công nhân của nhóm)
--   Tiền nhóm       = thùng vượt × đơn giá (1.000đ) × hệ số chuyền × hệ số nhóm
--   Chia cho công nhân trong nhóm theo giờ công; cuối tháng × hệ số lỗi Ki của từng người.
-- Vị trí nhóm trưởng / quản lý (đánh dấu `khong_thuong_vuot`) không nhận và không tính giờ.
-- Tiền tính trên app khi hiển thị, KHÔNG lưu DB (giống thưởng nhóm 085).
--
--   1. fp_var_bcnc_cai_dat_thuong  — đơn giá vượt + ngưỡng % theo nhà sơ chế
--   2. fp_var_bcnc_he_so_ns        — hệ số chuyền (so_nhom NULL) và hệ số nhóm mặc định (1–9)
--   3. fp_farm_bao_cao_nhan_cong_ct.he_so_nhom — hệ số nhóm sửa trên phiếu (ghi đè mặc định)
--   4. fp_var_vi_tri_so_che.khong_thuong_vuot  — vị trí không nhận thưởng vượt
--   5. fp_farm_bcnc_he_so_loi_thang — hệ số lỗi Ki theo tháng từng công nhân
--
-- Chạy: bash scripts/db-sql.sh -v ON_ERROR_STOP=1 -f docs/migrations/087-bcnc-thuong-vuot-thung.sql
-- =============================================================================
BEGIN;

-- 1) Cài đặt thưởng vượt theo nhà sơ chế.
CREATE TABLE IF NOT EXISTS public.fp_var_bcnc_cai_dat_thuong (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chi_nhanh bigint NOT NULL REFERENCES public.fp_var_chi_nhanh(id) ON DELETE CASCADE,
    don_gia_vuot numeric(12,2) DEFAULT 1000 NOT NULL,
    nguong_ns_pct numeric(5,2) DEFAULT 90 NOT NULL,
    tg_tao timestamp with time zone DEFAULT now() NOT NULL,
    tg_cap_nhat timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT fp_var_bcnc_cdt_don_gia_chk CHECK (don_gia_vuot >= 0),
    CONSTRAINT fp_var_bcnc_cdt_nguong_chk CHECK (nguong_ns_pct > 0 AND nguong_ns_pct <= 200)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_fp_var_bcnc_cdt_chi_nhanh ON public.fp_var_bcnc_cai_dat_thuong (id_chi_nhanh);
COMMENT ON TABLE public.fp_var_bcnc_cai_dat_thuong IS
  'Báo cáo nhân công — cài đặt thưởng vượt thùng theo nhà sơ chế; chưa có dòng = mặc định 1.000đ/thùng, ngưỡng 90%';
COMMENT ON COLUMN public.fp_var_bcnc_cai_dat_thuong.nguong_ns_pct IS
  'Ngưỡng tính vượt, % của mục tiêu NS phiếu (90 → 90% × 3 = 2,7 thùng/giờ-người)';

CREATE OR REPLACE TRIGGER trg_update_tg_cap_nhat BEFORE UPDATE ON public.fp_var_bcnc_cai_dat_thuong
  FOR EACH ROW EXECUTE FUNCTION public.update_tg_cap_nhat_column();

-- 2) Hệ số chuyền / nhóm theo nhà sơ chế.
CREATE TABLE IF NOT EXISTS public.fp_var_bcnc_he_so_ns (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chi_nhanh bigint NOT NULL REFERENCES public.fp_var_chi_nhanh(id) ON DELETE CASCADE,
    loai_chuyen text NOT NULL,
    so_nhom smallint,
    he_so numeric(6,3) NOT NULL,
    tg_tao timestamp with time zone DEFAULT now() NOT NULL,
    tg_cap_nhat timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT fp_var_bcnc_hsns_loai_chk CHECK (loai_chuyen IN
      ('XAN_NAI', 'TIA_DANH_GIA', 'CAN_TEM_DONG_THUNG', 'KHO_HUT_CHAN_KHONG', 'CONG_TANG_CUONG')),
    CONSTRAINT fp_var_bcnc_hsns_nhom_chk CHECK (so_nhom IS NULL OR so_nhom BETWEEN 1 AND 9),
    CONSTRAINT fp_var_bcnc_hsns_he_so_chk CHECK (he_so >= 0 AND he_so <= 100)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_fp_var_bcnc_hsns
  ON public.fp_var_bcnc_he_so_ns (id_chi_nhanh, loai_chuyen, coalesce(so_nhom, 0));
COMMENT ON TABLE public.fp_var_bcnc_he_so_ns IS
  'Báo cáo nhân công — hệ số thưởng vượt: so_nhom NULL = hệ số chuyền, 1–9 = hệ số nhóm mặc định; thiếu dòng = 1';

CREATE OR REPLACE TRIGGER trg_update_tg_cap_nhat BEFORE UPDATE ON public.fp_var_bcnc_he_so_ns
  FOR EACH ROW EXECUTE FUNCTION public.update_tg_cap_nhat_column();

-- 3) Hệ số nhóm trên phiếu (khoá "1".."9" → số 0–100); thiếu khoá = lấy mặc định Cài đặt.
CREATE OR REPLACE FUNCTION public.fn_bcnc_he_so_nhom_hop_le(v jsonb)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT jsonb_typeof(v) = 'object'
     AND NOT EXISTS (
       SELECT 1
       FROM jsonb_each(v) AS e(k, val)
       WHERE e.k !~ '^[1-9]$'
          OR jsonb_typeof(e.val) <> 'number'
          OR (e.val #>> '{}')::numeric < 0
          OR (e.val #>> '{}')::numeric > 100
     );
$$;
COMMENT ON FUNCTION public.fn_bcnc_he_so_nhom_hop_le(jsonb) IS 'CHECK cho fp_farm_bao_cao_nhan_cong_ct.he_so_nhom: object, khoá "1".."9", giá trị số 0–100';
REVOKE ALL ON FUNCTION public.fn_bcnc_he_so_nhom_hop_le(jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_bcnc_he_so_nhom_hop_le(jsonb) TO authenticated;

ALTER TABLE public.fp_farm_bao_cao_nhan_cong_ct
  ADD COLUMN IF NOT EXISTS he_so_nhom jsonb NOT NULL DEFAULT '{}'::jsonb;
ALTER TABLE public.fp_farm_bao_cao_nhan_cong_ct DROP CONSTRAINT IF EXISTS fp_farm_bcnc_ct_he_so_nhom_chk;
ALTER TABLE public.fp_farm_bao_cao_nhan_cong_ct
  ADD CONSTRAINT fp_farm_bcnc_ct_he_so_nhom_chk
  CHECK (jsonb_typeof(he_so_nhom) = 'object' AND public.fn_bcnc_he_so_nhom_hop_le(he_so_nhom));
COMMENT ON COLUMN public.fp_farm_bao_cao_nhan_cong_ct.he_so_nhom IS
  'Hệ số nhóm sửa trên phiếu: {"1": 1.2}; thiếu khoá = hệ số nhóm mặc định trong fp_var_bcnc_he_so_ns';

-- 4) Vị trí không nhận thưởng vượt (nhóm trưởng, nhóm phó, quản lý…).
ALTER TABLE public.fp_var_vi_tri_so_che
  ADD COLUMN IF NOT EXISTS khong_thuong_vuot boolean NOT NULL DEFAULT false;
COMMENT ON COLUMN public.fp_var_vi_tri_so_che.khong_thuong_vuot IS
  'true = người ở vị trí này không nhận thưởng vượt thùng và giờ công không tính vào định mức nhóm (đã có thưởng KPI)';

-- 5) Hệ số lỗi Ki theo tháng.
CREATE TABLE IF NOT EXISTS public.fp_farm_bcnc_he_so_loi_thang (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chi_nhanh bigint NOT NULL REFERENCES public.fp_var_chi_nhanh(id) ON DELETE CASCADE,
    thang date NOT NULL,
    khoa_nv text NOT NULL,
    id_nhan_vien bigint REFERENCES public.fp_var_nhan_vien_so_che(id) ON DELETE SET NULL,
    ho_ten text NOT NULL,
    he_so_loi numeric(4,2) DEFAULT 1 NOT NULL,
    ghi_chu text,
    tg_tao timestamp with time zone DEFAULT now() NOT NULL,
    tg_cap_nhat timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT fp_farm_bcnc_hslt_thang_chk CHECK (thang = date_trunc('month', thang)::date),
    CONSTRAINT fp_farm_bcnc_hslt_he_so_chk CHECK (he_so_loi >= 0 AND he_so_loi <= 2),
    CONSTRAINT fp_farm_bcnc_hslt_khoa_chk CHECK (btrim(khoa_nv) <> '')
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_fp_farm_bcnc_hslt
  ON public.fp_farm_bcnc_he_so_loi_thang (id_chi_nhanh, thang, khoa_nv);
COMMENT ON TABLE public.fp_farm_bcnc_he_so_loi_thang IS
  'Báo cáo nhân công — hệ số lỗi Ki theo tháng của từng công nhân (nhân vào thưởng vượt thùng tháng); thiếu dòng = 1';
COMMENT ON COLUMN public.fp_farm_bcnc_he_so_loi_thang.khoa_nv IS
  'Khoá người do app sinh: "nv:<id_nhan_vien>" hoặc "ten:<tên chuẩn hoá>" khi phiếu chưa gắn danh mục';

CREATE OR REPLACE TRIGGER trg_update_tg_cap_nhat BEFORE UPDATE ON public.fp_farm_bcnc_he_so_loi_thang
  FOR EACH ROW EXECUTE FUNCTION public.update_tg_cap_nhat_column();

-- 6) RLS + GRANT (khuôn migration 067). Ai xem phiếu thì xem; cài đặt hệ số + Ki chỉ người sửa/duyệt/quản trị.
DO $$
DECLARE
  c_mod constant text := 'quan-ly-nha-so-che/bao-cao-nhan-cong';
  c_xem constant text := 'ARRAY[''view'', ''create'', ''update'', ''delete'', ''approve'', ''admin'', ''all'']';
  c_sua constant text := 'ARRAY[''update'', ''approve'', ''admin'', ''all'']';
  r record;
BEGIN
  FOR r IN
    SELECT * FROM (VALUES
      ('fp_var_bcnc_cai_dat_thuong', 'fp_var_bcnc_cdt'),
      ('fp_var_bcnc_he_so_ns', 'fp_var_bcnc_hsns'),
      ('fp_farm_bcnc_he_so_loi_thang', 'fp_farm_bcnc_hslt')
    ) AS t(bang, ten)
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', r.bang);

    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_select_quyen', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_insert_quyen', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_update_quyen', r.bang);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.ten || '_delete_quyen', r.bang);

    EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_select_quyen', r.bang, c_mod, c_xem);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR INSERT TO authenticated '
                   'WITH CHECK ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_insert_quyen', r.bang, c_mod, c_sua);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR UPDATE TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s))) '
                   'WITH CHECK ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_update_quyen', r.bang, c_mod, c_sua, c_mod, c_sua);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR DELETE TO authenticated '
                   'USING ((SELECT public.fn_co_quyen_module(%L, %s)))',
                   r.ten || '_delete_quyen', r.bang, c_mod, c_sua);

    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon', r.bang);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.%I TO authenticated', r.bang);
    EXECUTE format('REVOKE ALL ON SEQUENCE public.%I FROM PUBLIC, anon', r.bang || '_id_seq');
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE public.%I TO authenticated', r.bang || '_id_seq');

    -- Nhật ký thay đổi (migration 016) — ai đổi hệ số / Ki là ảnh hưởng tiền thưởng.
    EXECUTE format('CREATE OR REPLACE TRIGGER trg_nhat_ky_thay_doi AFTER INSERT OR UPDATE OR DELETE ON public.%I '
                   'FOR EACH ROW EXECUTE FUNCTION public.fn_ghi_nhat_ky_thay_doi()', r.bang);
  END LOOP;
END;
$$;

COMMIT;

