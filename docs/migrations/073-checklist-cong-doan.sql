-- 8) RPC đổi trạng thái -------------------------------------------------------------------
-- SECURITY DEFINER (bỏ qua trigger khoá) nên tự kiểm quyền; khoá dòng FOR UPDATE, kiểm trạng thái mong đợi.
CREATE OR REPLACE FUNCTION public.rpc_cl_chuyen(p_id bigint) RETURNS text
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  p public.fp_farm_cl_phieu%ROWTYPE;
  v_thieu integer;
  v_thieu_kp integer;
  v_den text;
BEGIN
  SELECT * INTO p FROM public.fp_farm_cl_phieu WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Không tìm thấy phiếu checklist.' USING ERRCODE = 'P0001'; END IF;
  IF p.trang_thai NOT IN ('nhap', 'tra_lai') THEN
    RAISE EXCEPTION 'Phiếu % không ở trạng thái nháp / bị trả lại.', p.so_phieu USING ERRCODE = 'P0001';
  END IF;
  IF NOT (public.fn_cl_la_cap_cao() OR public.fn_cl_la_ben_thuc_hien(p.chuc_vu_thuc_hien_ids, p.id_nguoi_tao)) THEN
    RAISE EXCEPTION 'Bạn không thuộc "%" của phiếu %.', p.ten_ben_thuc_hien, p.so_phieu USING ERRCODE = 'P0001';
  END IF;

  SELECT count(*) FILTER (WHERE kq_thuc_hien IS NULL),
         count(*) FILTER (WHERE kq_thuc_hien = 'khong_dat' AND nullif(btrim(coalesce(tinh_trang_khac_phuc, '')), '') IS NULL)
    INTO v_thieu, v_thieu_kp
    FROM public.fp_farm_cl_phieu_dong WHERE id_phieu = p.id;
  IF v_thieu > 0 THEN
    RAISE EXCEPTION 'Còn % hạng mục chưa tích Đạt / Không đạt.', v_thieu USING ERRCODE = 'P0001';
  END IF;
  IF v_thieu_kp > 0 THEN
    RAISE EXCEPTION 'Còn % hạng mục Không đạt chưa ghi tình trạng & biện pháp khắc phục.', v_thieu_kp USING ERRCODE = 'P0001';
  END IF;
  IF p.co_ket_luan_van_hanh AND p.ket_luan IS NULL THEN
    RAISE EXCEPTION 'Chọn kết luận tình trạng vận hành trước khi chuyển.' USING ERRCODE = 'P0001';
  END IF;

  v_den := CASE WHEN cardinality(coalesce(p.chuc_vu_kiem_tra_ids, '{}')) > 0 THEN 'cho_kiem_tra' ELSE 'hoan_thanh' END;

  -- Khâu sau kiểm tra lại từ đầu mỗi lần nhận phiếu.
  UPDATE public.fp_farm_cl_phieu_dong SET kq_kiem_tra = NULL WHERE id_phieu = p.id AND kq_kiem_tra IS NOT NULL;

  PERFORM set_config('farm.cl_ly_do', '', true);
  UPDATE public.fp_farm_cl_phieu
     SET trang_thai = v_den,
         id_nguoi_chuyen = public.nhan_vien_hien_tai_id(), tg_chuyen = now(),
         id_nguoi_nhan = CASE WHEN v_den = 'hoan_thanh' THEN public.nhan_vien_hien_tai_id() END,
         tg_nhan = CASE WHEN v_den = 'hoan_thanh' THEN now() END
   WHERE id = p.id;
  RETURN v_den;
END
$$;

CREATE OR REPLACE FUNCTION public.rpc_cl_nhan(p_id bigint) RETURNS text
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  p public.fp_farm_cl_phieu%ROWTYPE;
  v_thieu integer;
BEGIN
  SELECT * INTO p FROM public.fp_farm_cl_phieu WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Không tìm thấy phiếu checklist.' USING ERRCODE = 'P0001'; END IF;
  IF p.trang_thai <> 'cho_kiem_tra' THEN
    RAISE EXCEPTION 'Phiếu % không ở trạng thái chờ kiểm tra lại.', p.so_phieu USING ERRCODE = 'P0001';
  END IF;
  IF NOT (public.fn_cl_la_cap_cao() OR public.fn_cl_la_ben_kiem_tra(p.chuc_vu_kiem_tra_ids)) THEN
    RAISE EXCEPTION 'Bạn không thuộc "%" của phiếu %.', p.ten_ben_kiem_tra, p.so_phieu USING ERRCODE = 'P0001';
  END IF;
  SELECT count(*) FILTER (WHERE kq_kiem_tra IS NULL) INTO v_thieu
    FROM public.fp_farm_cl_phieu_dong WHERE id_phieu = p.id;
  IF v_thieu > 0 THEN
    RAISE EXCEPTION 'Còn % hạng mục chưa kiểm tra lại.', v_thieu USING ERRCODE = 'P0001';
  END IF;

  PERFORM set_config('farm.cl_ly_do', '', true);
  UPDATE public.fp_farm_cl_phieu
     SET trang_thai = 'hoan_thanh', id_nguoi_nhan = public.nhan_vien_hien_tai_id(), tg_nhan = now()
   WHERE id = p.id;
  RETURN 'hoan_thanh';
END
$$;

