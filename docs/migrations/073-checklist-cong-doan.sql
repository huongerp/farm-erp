-- (Sản xuất gồm cả QC, Giám sát, Nhóm trưởng…). Bên thực hiện rỗng = ai có quyền tạo phiếu.
-- Bên kiểm tra lại: chỉ nhân viên có chức vụ trong danh sách (hoặc cấp cao) mới tích cột kiểm
-- tra, bấm Nhận / Trả lại. Trạng thái chỉ đổi qua RPC rpc_cl_* (ghi lịch sử, thông báo).
-- Chặn ở trigger khi current_user = 'authenticated' (PostgREST); SQL tay / RPC definer không bị chặn.
