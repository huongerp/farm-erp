-- Mở lại (cấp cao): hoan_thanh → cho_kiem_tra (hoặc nhap nếu không có khâu sau); huy → nhap.
CREATE OR REPLACE FUNCTION public.rpc_cl_mo_lai(p_id bigint, p_ly_do text) RETURNS text
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  p public.fp_farm_cl_phieu%ROWTYPE;
  v_den text;
BEGIN
  IF NOT public.fn_cl_la_cap_cao() THEN
    RAISE EXCEPTION 'Chỉ quản trị / cấp cao mới mở lại phiếu.' USING ERRCODE = 'P0001';
  END IF;
  IF nullif(btrim(coalesce(p_ly_do, '')), '') IS NULL THEN
    RAISE EXCEPTION 'Nhập lý do mở lại.' USING ERRCODE = 'P0001';
  END IF;
  SELECT * INTO p FROM public.fp_farm_cl_phieu WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Không tìm thấy phiếu checklist.' USING ERRCODE = 'P0001'; END IF;
  IF p.trang_thai NOT IN ('hoan_thanh', 'huy') THEN
    RAISE EXCEPTION 'Chỉ mở lại phiếu đã hoàn thành / đã huỷ.' USING ERRCODE = 'P0001';
  END IF;
  v_den := CASE
    WHEN p.trang_thai = 'huy' THEN 'nhap'
    WHEN cardinality(coalesce(p.chuc_vu_kiem_tra_ids, '{}')) > 0 THEN 'cho_kiem_tra'
    ELSE 'nhap' END;
