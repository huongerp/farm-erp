-- Hạn kế tiếp: khớp bao-duong-thiet-bi/core/han.ts (hanKeTiep).
CREATE OR REPLACE FUNCTION public.fn_farm_bd_tinh_han() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'public'
    AS $$
BEGIN
  IF NEW.chu_ky_ngay IS NULL THEN
    NEW.han_ke_tiep := NULL;
  ELSIF NEW.lan_gan_nhat IS NOT NULL THEN
    NEW.han_ke_tiep := NEW.lan_gan_nhat + NEW.chu_ky_ngay;
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER trg_farm_bd_tinh_han BEFORE INSERT OR UPDATE ON public.fp_farm_bd_viec
  FOR EACH ROW EXECUTE FUNCTION public.fn_farm_bd_tinh_han();

-- Nhật ký đổi → lan_gan_nhat = ngày làm gần nhất. SECURITY DEFINER: người ghi nhật ký
-- (quyền create) không cần quyền update trên bảng việc.
CREATE OR REPLACE FUNCTION public.fn_farm_bd_dong_bo_lan_gan_nhat() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  v_id bigint;
BEGIN
  FOR v_id IN
    SELECT DISTINCT x FROM unnest(ARRAY[
      CASE WHEN TG_OP <> 'INSERT' THEN OLD.id_viec END,
      CASE WHEN TG_OP <> 'DELETE' THEN NEW.id_viec END]) AS x
    WHERE x IS NOT NULL
  LOOP
    UPDATE public.fp_farm_bd_viec v
       SET lan_gan_nhat = (SELECT max(nk.ngay_thuc_hien) FROM public.fp_farm_bd_nhat_ky nk WHERE nk.id_viec = v_id)
     WHERE v.id = v_id;
  END LOOP;
  RETURN NULL;
END
$$;
REVOKE ALL ON FUNCTION public.fn_farm_bd_dong_bo_lan_gan_nhat() FROM PUBLIC, anon;
CREATE TRIGGER trg_farm_bd_dong_bo_lan_gan_nhat
  AFTER INSERT OR UPDATE OF ngay_thuc_hien, id_viec OR DELETE ON public.fp_farm_bd_nhat_ky
  FOR EACH ROW EXECUTE FUNCTION public.fn_farm_bd_dong_bo_lan_gan_nhat();

CREATE OR REPLACE FUNCTION public.fn_farm_bd_dien_nguoi_tao() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'public'
    AS $$
BEGIN
  IF NEW.id_nguoi_tao IS NULL THEN
    NEW.id_nguoi_tao := public.nhan_vien_hien_tai_id();
  END IF;
  RETURN NEW;
END
$$;
