--   nhap ──Chuyển──▶ cho_kiem_tra ──Nhận──▶ hoan_thanh ──Mở lại (cấp cao)──▶ cho_kiem_tra
--     ▲                   │
--     └──── tra_lai ◀─────┘ Trả lại (lý do bắt buộc)
