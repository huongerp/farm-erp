--
-- Trước đây farm nhập hệ số quy đổi trên từng dòng phiếu (086). Nay quản trị cài sẵn hệ số
-- mặc định theo chi nhánh (farm) × tên phẩm cấp; form phiếu tự điền, farm thường không phải chọn.
-- Thiếu dòng = farm chưa cài phẩm cấp đó → form giữ hành vi cũ (gợi ý từ lịch sử phiếu).
-- Chỉ admin/all được ghi (RLS); người có quyền xem phiếu vẫn đọc được để form tự điền.
--
-- Chạy: bash scripts/db-sql.sh -v ON_ERROR_STOP=1 -f docs/migrations/092-bcsc-cai-dat-he-so-quy-doi.sql
-- =============================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS public.fp_var_bcsc_he_so_quy_doi (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chi_nhanh bigint NOT NULL REFERENCES public.fp_var_chi_nhanh(id) ON DELETE CASCADE,
    ten_pham_cap text NOT NULL,
    he_so_quy_doi numeric(8,4) NOT NULL,
    tg_tao timestamp with time zone DEFAULT now() NOT NULL,
    tg_cap_nhat timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT fp_var_bcsc_hsqd_ten_chk CHECK (btrim(ten_pham_cap) <> ''),
    CONSTRAINT fp_var_bcsc_hsqd_he_so_chk CHECK (he_so_quy_doi >= 0 AND he_so_quy_doi <= 9999)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_fp_var_bcsc_hsqd
  ON public.fp_var_bcsc_he_so_quy_doi (id_chi_nhanh, lower(btrim(ten_pham_cap)));
COMMENT ON TABLE public.fp_var_bcsc_he_so_quy_doi IS
  'Báo cáo sơ chế — hệ số quy đổi mặc định theo farm (chi nhánh) × phẩm cấp; thiếu dòng = farm chưa cài';
COMMENT ON COLUMN public.fp_var_bcsc_he_so_quy_doi.he_so_quy_doi IS
  'Hệ số mặc định theo farm × phẩm cấp, form phiếu tự điền (so_thung_quy_doi = so_thung × hệ số); thiếu dòng = farm chưa cài';

CREATE OR REPLACE TRIGGER trg_update_tg_cap_nhat BEFORE UPDATE ON public.fp_var_bcsc_he_so_quy_doi
  FOR EACH ROW EXECUTE FUNCTION public.update_tg_cap_nhat_column();

-- RLS + GRANT (khuôn migration 013/087): ai xem phiếu sơ chế thì đọc được cài đặt;
-- chỉ quản trị (admin/all) mới được thêm / sửa / xoá.
DO $$
DECLARE
  c_mod constant text := 'quan-ly-nha-so-che/bao-cao-so-che';
  c_xem constant text := 'ARRAY[''view'', ''create'', ''update'', ''delete'', ''approve'', ''admin'', ''all'']';
  c_sua constant text := 'ARRAY[''admin'', ''all'']';
BEGIN
  EXECUTE 'ALTER TABLE public.fp_var_bcsc_he_so_quy_doi ENABLE ROW LEVEL SECURITY';

  EXECUTE 'DROP POLICY IF EXISTS bcsc_hsqd_select_quyen ON public.fp_var_bcsc_he_so_quy_doi';
  EXECUTE 'DROP POLICY IF EXISTS bcsc_hsqd_insert_quyen ON public.fp_var_bcsc_he_so_quy_doi';
  EXECUTE 'DROP POLICY IF EXISTS bcsc_hsqd_update_quyen ON public.fp_var_bcsc_he_so_quy_doi';
  EXECUTE 'DROP POLICY IF EXISTS bcsc_hsqd_delete_quyen ON public.fp_var_bcsc_he_so_quy_doi';

  EXECUTE format('CREATE POLICY %I ON public.fp_var_bcsc_he_so_quy_doi FOR SELECT TO authenticated '
                 'USING ((SELECT public.fn_co_quyen_module(%L, %s)))',
                 'bcsc_hsqd_select_quyen', c_mod, c_xem);
  EXECUTE format('CREATE POLICY %I ON public.fp_var_bcsc_he_so_quy_doi FOR INSERT TO authenticated '
                 'WITH CHECK ((SELECT public.fn_co_quyen_module(%L, %s)))',
                 'bcsc_hsqd_insert_quyen', c_mod, c_sua);
  EXECUTE format('CREATE POLICY %I ON public.fp_var_bcsc_he_so_quy_doi FOR UPDATE TO authenticated '
                 'USING ((SELECT public.fn_co_quyen_module(%L, %s))) '
                 'WITH CHECK ((SELECT public.fn_co_quyen_module(%L, %s)))',
                 'bcsc_hsqd_update_quyen', c_mod, c_sua, c_mod, c_sua);
  EXECUTE format('CREATE POLICY %I ON public.fp_var_bcsc_he_so_quy_doi FOR DELETE TO authenticated '
                 'USING ((SELECT public.fn_co_quyen_module(%L, %s)))',
                 'bcsc_hsqd_delete_quyen', c_mod, c_sua);

  EXECUTE 'REVOKE ALL ON TABLE public.fp_var_bcsc_he_so_quy_doi FROM PUBLIC, anon';
  EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.fp_var_bcsc_he_so_quy_doi TO authenticated';
  EXECUTE 'REVOKE ALL ON SEQUENCE public.fp_var_bcsc_he_so_quy_doi_id_seq FROM PUBLIC, anon';
  EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE public.fp_var_bcsc_he_so_quy_doi_id_seq TO authenticated';

  -- Nhật ký thay đổi (migration 016) — đổi hệ số ảnh hưởng số quy đổi của mọi phiếu.
  EXECUTE 'CREATE OR REPLACE TRIGGER trg_nhat_ky_thay_doi AFTER INSERT OR UPDATE OR DELETE '
          'ON public.fp_var_bcsc_he_so_quy_doi FOR EACH ROW '
          'EXECUTE FUNCTION public.fn_ghi_nhat_ky_thay_doi()';
END;
$$;

COMMIT;

